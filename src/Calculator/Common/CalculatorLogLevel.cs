/// </summary>
public enum CalculatorLogLevel
{
    /// <summary>
    /// An informational event.
    /// </summary>
    Information,

    /// <summary>
    /// A warning event.
    /// </summary>
    Warning,

    /// <summary>
    /// An error event.
    /// </summary>
    Error,
}
