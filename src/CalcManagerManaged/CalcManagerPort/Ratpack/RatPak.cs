    //---------------------------------------------------------------------------
    //
    //  FUNCTION: trimit
    //
    //  ARGUMENTS:  PRAT *px, int32_t precision
    //
    //
    //  DESCRIPTION: Chops off digits from rational numbers to avoid time
    //  explosions in calculations of functions using series.
    //  It can be shown that it is enough to only keep the first n digits
    //  of the largest of p or q in the rational p over q form, and of course
    //  scale the smaller by the same number of digits.  This will give you
    //  n-1 digits of accuracy.  This dramatically speeds up calculations
    //  involving hundreds of digits or more.
    //  The last part of this trim dealing with exponents never affects accuracy
    //
    //  RETURN: none, modifies the pointed to PRAT
    //
    //---------------------------------------------------------------------------
    void trimit(ref PRAT px, int32_t precision)
    {
        if (!g_ftrueinfinite)
        {
            PNUMBER pp = px._pp;
            PNUMBER pq = px._pq;

            int32_t trim = g_ratio * (Math.Min((pp._cdigit + pp._exp), (pq._cdigit + pq._exp)) - 1) - precision;

            if (trim > g_ratio)
            {
                trim /= g_ratio;

                if (trim <= pp._exp)
                {
                    pp._exp -= trim;
                }
                else
                {
                    Array.Copy(pp._mant, trim - pp._exp, pp._mant, 0, pp._cdigit - trim + pp._exp);
                    pp._cdigit -= trim - pp._exp;
                    pp._exp = 0;
                }

                if (trim <= pq._exp)
                {
                    pq._exp -= trim;
                }
                else
                {
                    Array.Copy(pq._mant, trim - pq._exp, pq._mant, 0, pq._cdigit - trim + pq._exp);
                    pq._cdigit -= trim - pq._exp;
                    pq._exp = 0;
                }
            }

            trim = Math.Min(pp._exp, pq._exp);
            pp._exp -= trim;
            pq._exp -= trim;
        }
    }

    // Helper function for sin/cos Taylor series term - implements the NEXTTERM macro for trigonometric functions
    void SIN_COS_RAT_NEXTTERM(ref RAT thisterm, ref RAT xx, ref NUMBER n2, int32_t precision, ref RAT pret)
    {
        // First multiply thisterm by xx (the -x² value)
        mulrat(ref thisterm, xx, precision);

        // Execute the operations from the d parameter: INC(n2) DIVNUM(n2) INC(n2) DIVNUM(n2)
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);

        // Add the result to pret
        addrat(ref pret, thisterm, precision);
    }

    public void scalerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        switch (angletype)
        {
            case AngleType.Radians:
                scale2pi(ref pa, radix, precision);
                break;
            case AngleType.Degrees:
                scale(ref pa, rat_360, radix, precision);
                break;
            case AngleType.Gradians:
                scale(ref pa, rat_400, radix, precision);
                break;
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: sinrat, _sinrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the sine of
    //
    //  RETURN: sin of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___          2j+1
    //   \  ]   j    X
    //    \   -1  * ---------
    //    /          (2j+1)!
    //   /__]
    //   j=0
    //          or,
    //    n
    //   ___                                                 2
    //   \  ]                                              -X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j   (2j)*(2j+1)
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //-----------------------------------------------------------------------------

    void _sinrat(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        duprat(ref pret, px);
        duprat(ref thisterm, px);

        dupnum(ref n2, num_one);
        xx._pp._sign *= -1;

        do
        {
            SIN_COS_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);

        // Since px might be epsilon above 1 or below -1, due to TRIMIT we need
        // this trick here.
        inbetween(ref px, rat_one, precision);

        // Since px might be epsilon near zero we must set it to zero.
        if (rat_le(px, rat_smallest, precision) && rat_ge(px, rat_negsmallest, precision))
        {
            duprat(ref px, rat_zero);
        }
    }

    public void sinrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        scale2pi(ref px, radix, precision);
        _sinrat(ref px, precision);
    }

    public void sinanglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        scalerat(ref pa, angletype, radix, precision);
        switch (angletype)
        {
            case AngleType.Degrees:
                if (RatGt(pa, rat_180, precision))
                {
                    subrat(ref pa, rat_360, precision);
                }
                divrat(ref pa, rat_180, precision);
                mulrat(ref pa, _pi, precision);
                break;
            case AngleType.Gradians:
                if (RatGt(pa, rat_200, precision))
                {
                    subrat(ref pa, rat_400, precision);
                }
                divrat(ref pa, rat_200, precision);
                mulrat(ref pa, _pi, precision);
                break;
        }
        _sinrat(ref pa, precision);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: cosrat, _cosrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the cosine of
    //
    //  RETURN: cosine of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___    2j   j
    //   \  ]  X   -1
    //    \   ---------
    //    /    (2j)!
    //   /__]
    //   j=0
    //          or,
    //    n
    //   ___                                                 2
    //   \  ]                                              -X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j   (2j)*(2j+1)
    //   /__]
    //   j=0
    //
    //   thisterm  = 1 ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //-----------------------------------------------------------------------------

    void _cosrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        pret._pp = i32tonum(1, radix);
        pret._pq = i32tonum(1, radix);

        duprat(ref thisterm, pret);

        n2 = i32tonum(0, radix);
        xx._pp._sign *= -1;

        do
        {
            SIN_COS_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);

        // Since px might be epsilon above 1 or below -1, due to TRIMIT we need
        // this trick here.
        inbetween(ref px, rat_one, precision);

        // Since px might be epsilon near zero we must set it to zero.
        if (rat_le(px, rat_smallest, precision) && rat_ge(px, rat_negsmallest, precision))
        {
            duprat(ref px, rat_zero);
        }
    }

    public void cosrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        scale2pi(ref px, radix, precision);
        _cosrat(ref px, radix, precision);
    }

    public void cosanglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        scalerat(ref pa, angletype, radix, precision);
        switch (angletype)
        {
            case AngleType.Degrees:
                if (RatGt(pa, rat_180, precision))
                {
                    PRAT? ptmp = null;
                    duprat(ref ptmp, rat_360);
                    subrat(ref ptmp, pa, precision);
                    pa = ptmp;
                }
                divrat(ref pa, rat_180, precision);
                mulrat(ref pa, _pi, precision);
                break;
            case AngleType.Gradians:
                if (RatGt(pa, rat_200, precision))
                {
                    PRAT? ptmp = null;
                    duprat(ref ptmp, rat_400);
                    subrat(ref ptmp, pa, precision);
                    pa = ptmp;
                }
                divrat(ref pa, rat_200, precision);
                mulrat(ref pa, _pi, precision);
                break;
        }
        _cosrat(ref pa, radix, precision);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: tanrat, _tanrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the tangent of
    //
    //  RETURN: tan of x in PRAT form.
    //
    //  EXPLANATION: This uses sinrat and cosrat
    //
    //-----------------------------------------------------------------------------

    void _tanrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT? ptmp = null;

        duprat(ref ptmp, px);
        _sinrat(ref px, precision);
        _cosrat(ref ptmp, radix, precision);
        if (zerrat(ptmp))
        {
            destroyrat(ref ptmp);
            throw new CalcErrException(CalcErr.Domain);
        }
        divrat(ref px, ptmp, precision);

        destroyrat(ref ptmp);
    }

    public void tanrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        scale2pi(ref px, radix, precision);
        _tanrat(ref px, radix, precision);
    }

    public void tananglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        scalerat(ref pa, angletype, radix, precision);
        switch (angletype)
        {
            case AngleType.Degrees:
                if (RatGt(pa, rat_180, precision))
                {
                    subrat(ref pa, rat_180, precision);
                }
                divrat(ref pa, rat_180, precision);
                mulrat(ref pa, _pi, precision);
                break;
            case AngleType.Gradians:
                if (RatGt(pa, rat_200, precision))
                {
                    subrat(ref pa, rat_200, precision);
                }
                divrat(ref pa, rat_200, precision);
                mulrat(ref pa, _pi, precision);
                break;
        }
        _tanrat(ref pa, radix, precision);
    }

    // Helper function for hyperbolic Taylor series term - implements the NEXTTERM macro for hyperbolic functions
    void HYP_RAT_NEXTTERM(ref RAT thisterm, ref RAT xx, ref NUMBER n2, int32_t precision, ref RAT pret)
    {
        // First multiply thisterm by xx
        mulrat(ref thisterm, xx, precision);

        // Execute the operations from the d parameter: INC(n2) DIVNUM(n2) INC(n2) DIVNUM(n2)
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);

        // Add the result to pret
        addrat(ref pret, thisterm, precision);
    }

    bool IsValidForHypFunc(PRAT px, int32_t precision)
    {
        PRAT? ptmp = null;
        bool bRet = true;

        duprat(ref ptmp, rat_min_exp);
        divrat(ref ptmp, rat_ten, precision);
        if (RatLt(px, ptmp, precision))
        {
            bRet = false;
        }
        destroyrat(ref ptmp);
        return bRet;
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: sinhrat, _sinhrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the sine hyperbolic
    //    of
    //  RETURN: sinh of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___    2j+1
    //   \  ]  X
    //    \   ---------
    //    /    (2j+1)!
    //   /__]
    //   j=0
    //          or,
    //    n
    //   ___                                                 2
    //   \  ]                                               X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j   (2j)*(2j+1)
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   if x is bigger than 1.0 (e^x-e^-x)/2 is used.
    //
    //-----------------------------------------------------------------------------

    void _sinhrat(ref PRAT px, int32_t precision)
    {
        if (!IsValidForHypFunc(px, precision))
        {
            // Don't attempt exp of anything large or small
            throw new CalcErrException(CalcErr.Domain);
        }

        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        duprat(ref pret, px);
        duprat(ref thisterm, pret);

        dupnum(ref n2, num_one);

        do
        {
            HYP_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void sinhrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT? tmpx = null;

        if (rat_ge(px, rat_one, precision))
        {
            duprat(ref tmpx, px);
            exprat(ref px, radix, precision);
            tmpx._pp._sign *= -1;
            exprat(ref tmpx, radix, precision);
            subrat(ref px, tmpx, precision);
            divrat(ref px, rat_two, precision);
            destroyrat(ref tmpx);
        }
        else
        {
            _sinhrat(ref px, precision);
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: coshrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the cosine
    //              hyperbolic of
    //
    //  RETURN: cosh  of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___    2j
    //   \  ]  X
    //    \   ---------
    //    /    (2j)!
    //   /__]
    //   j=0
    //          or,
    //    n
    //   ___                                                 2
    //   \  ]                                               X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j   (2j)*(2j+1)
    //   /__]
    //   j=0
    //
    //   thisterm  = 1 ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   if x is bigger than 1.0 (e^x+e^-x)/2 is used.
    //
    //-----------------------------------------------------------------------------

    void _coshrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (!IsValidForHypFunc(px, precision))
        {
            // Don't attempt exp of anything large or small
            throw new CalcErrException(CalcErr.Domain);
        }

        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        pret._pp = i32tonum(1, radix);
        pret._pq = i32tonum(1, radix);

        duprat(ref thisterm, pret);

        n2 = i32tonum(0, radix);

        do
        {
            HYP_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void coshrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        PRAT? tmpx = null;

        px._pp._sign = 1;
        px._pq._sign = 1;
        if (rat_ge(px, rat_one, precision))
        {
            duprat(ref tmpx, px);
            exprat(ref px, radix, precision);
            tmpx._pp._sign *= -1;
            exprat(ref tmpx, radix, precision);
            addrat(ref px, tmpx, precision);
            divrat(ref px, rat_two, precision);
            destroyrat(ref tmpx);
        }
        else
        {
            _coshrat(ref px, radix, precision);
        }
        // Since px might be epsilon below 1 due to TRIMIT
        // we need this trick here.
        if (RatLt(px, rat_one, precision))
        {
            duprat(ref px, rat_one);
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: tanhrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the tangent
    //              hyperbolic of
    //
    //  RETURN: tanh of x in PRAT form.
    //
    //  EXPLANATION: This uses sinhrat and coshrat
    //
    //-----------------------------------------------------------------------------

    public void tanhrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT? ptmp = null;

        duprat(ref ptmp, px);
        sinhrat(ref px, radix, precision);
        coshrat(ref ptmp, radix, precision);
        mulnumx(ref (px._pp), ptmp._pq);
        mulnumx(ref (px._pq), ptmp._pp);

        destroyrat(ref ptmp);
    }
