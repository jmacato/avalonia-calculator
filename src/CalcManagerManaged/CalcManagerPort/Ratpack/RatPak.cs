    //
    //    RETURN: pointer to a number
    //
    //    DESCRIPTION: allocates and zeros out number type.
    //
    //-----------------------------------------------------------------------------
    private static PNUMBER _createnum(uint32_t size)
    {
        PNUMBER pnumret;
        uint32_t cbAlloc;
        uint32_t mantissaLength;

        // sizeof( MANTTYPE ) is the size of a 'digit'
        if (SUCCEEDED(Calc_ULongAdd(size, 1, out cbAlloc)) &&
            SUCCEEDED(Calc_ULongMult(cbAlloc, (uint32_t)sizeof(MANTTYPE), out cbAlloc))
            && SUCCEEDED(Calc_ULongAdd(cbAlloc, NUMBER.ConstSizeOf, out cbAlloc))
            && SUCCEEDED(Calc_ULongAdd(size, 9, out mantissaLength))
            && mantissaLength <= int.MaxValue)
        {

            pnumret = new PNUMBER
            {
                _mant = new uint32_t[(int)mantissaLength]
            };
        }
        else
        {
            throw new CalcErrException(CalcErr.InvalidRange);
        }

        return (pnumret);
    }

