    //---------------------------------------------------------------------------
    //
    //    FUNCTION: boolnum
    //
    //    ARGUMENTS: pointer to a number a second number
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the number equivalent of *pa &= b.
    //    radix doesn't matter for logicals.
    //    WARNING: Assumes numbers are unsigned.
    //
    //---------------------------------------------------------------------------

    static void boolnum(ref PNUMBER pa, PNUMBER b, int func)
    {
        PNUMBER? c = null;
        PNUMBER? a = null;
        MANTTYPE[] pcha;
        MANTTYPE[] pchb;
        MANTTYPE[] pchc;
        MANTTYPE pchaCnt = 0;
        MANTTYPE pchbCnt = 0;
        MANTTYPE pchcCnt = 0;
        int32_t cdigits;
        int32_t mexp;
        MANTTYPE da;
        MANTTYPE db;

        a = pa;
        cdigits = Math.Max(a._cdigit + a._exp, b._cdigit + b._exp) - Math.Min(a._exp, b._exp);
        createnum(ref c, (uint32_t)cdigits);

        c._exp = Math.Min(a._exp, b._exp);
        mexp = c._exp;
        c._cdigit = cdigits;
        pcha = a._mant;
        pchb = b._mant;
        pchc = c._mant;
        for (; cdigits > 0; cdigits--, mexp++)
        {
            da = (((mexp >= a._exp) && (cdigits + a._exp - c._exp > (c._cdigit - a._cdigit))) ? pcha[pchaCnt++] : 0);
            db = (((mexp >= b._exp) && (cdigits + b._exp - c._exp > (c._cdigit - b._cdigit))) ? pchb[pchbCnt++] : 0);
            switch (func)
            {
                case (int)BoolFuncs.FUNC_AND:
                    pchc[pchcCnt++] = da & db;
                    break;
                case (int)BoolFuncs.FUNC_OR:
                    pchc[pchcCnt++] = da | db;
                    break;
                case (int)BoolFuncs.FUNC_XOR:
                    pchc[pchcCnt++] = da ^ db;
                    break;
            }
        }

        c._sign = a._sign;
        while (c._cdigit > 1 && pchc[--pchcCnt] == 0)
        {
            c._cdigit--;
        }

        pa = c;
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: remrat
    //
    //    ARGUMENTS: pointer to a rational a second rational.
    //
    //    RETURN: None, changes pointer.
    //
    //    DESCRIPTION: Calculate the remainder of *pa / b,
    //                 equivalent of 'pa % b' in C/C++ and produces a result
    //                 that is either zero or has the same sign as the dividend.
    //
    //-----------------------------------------------------------------------------

    public static void remrat(ref PRAT pa, PRAT b)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (zerrat(b))
        {
            throw new CalcErrException(CalcErr.Indefinite);
        }

        PRAT? tmp = null;
        duprat(ref tmp, b);

        mulnumx(ref ((pa)._pp), tmp._pq);
        mulnumx(ref (tmp._pp), (pa)._pq);
        remnum(ref ((pa)._pp), tmp._pp, BASEX);
        mulnumx(ref ((pa)._pq), tmp._pq);

        // Get *pa back in the integer over integer form.
        RENORMALIZE(pa);

        destroyrat(ref tmp);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: modrat
    //
    //    ARGUMENTS: pointer to a rational a second rational.
    //
    //    RETURN: None, changes pointer.
    //
    //    DESCRIPTION: Calculate the remainder of *pa / b, with the sign of the result
    //                 either zero or has the same sign as the divisor.
    //    NOTE: When *pa or b are negative, the result won't be the same as
    //          the C/C++ operator %, use remrat if it's the behavior you expect.
    //
    //-----------------------------------------------------------------------------

    public void modrat(ref PRAT pa, PRAT b)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        // contrary to remrat(X, 0) returning 0, modrat(X, 0) must return X
        if (zerrat(b))
        {
            return;
        }

        PRAT? tmp = null;
        duprat(ref tmp, b);

        var needAdjust = (SIGN(pa) == -1 ? (SIGN(b) == 1) : (SIGN(b) == -1));

        mulnumx(ref ((pa)._pp), tmp._pq);
        mulnumx(ref (tmp._pp), (pa)._pq);
        remnum(ref ((pa)._pp), tmp._pp, BASEX);
        mulnumx(ref ((pa)._pq), tmp._pq);

        if (needAdjust && !zerrat(pa))
        {
            addrat(ref pa, b, unchecked((int32_t)BASEX));
        }

        // Get *pa back in the integer over integer form.
        RENORMALIZE(pa);

        destroyrat(ref tmp);
    }

    //----------------------------------------------------------------------------
    //
    //    FUNCTION: addnum
    //
    //    ARGUMENTS: pointer to a number a second number, and the
    //               radix.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the number equivalent of *pa += b.
    //    Assumes radix is the base of both numbers.
    //
    //    ALGORITHM: Adds each digit from least significant to most
    //    significant.
    //
    //
    //----------------------------------------------------------------------------
    public static void addnum(ref PNUMBER pa, PNUMBER b, uint32_t radix)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        if (b._cdigit > 1 || b._mant[0] != 0)
        {
            // If b is zero we are done.
            if (pa._cdigit > 1 || (pa)._mant[0] != 0)
            {
                // pa and b are both nonzero.
                _addnum(ref pa, b, radix);
            }
            else
            {
                // if pa is zero and b isn't just copy b.
                dupnum(ref pa, b);
            }
        }
    }

    static void _addnum(ref PNUMBER pa, PNUMBER b, uint32_t radix)
    {
        PNUMBER? c = null; // c will contain the result.
        PNUMBER? a = null; // a is the dereferenced number pointer from *pa
        MANTTYPE[] pcha; // pcha is a pointer to the mantissa of a.
        MANTTYPE[] pchb; // pchb is a pointer to the mantissa of b.
        MANTTYPE[] pchc; // pchc is a pointer to the mantissa of c.

        int32_t pchaCnt = 0, pchbCnt = 0, pchcCnt = 0;

        int32_t cdigits; // cdigits is the max count of the digits results used as a counter.
        int32_t mexp; // mexp is the exponent of the result.
        MANTTYPE da; // da is a single 'digit' after possible padding.
        MANTTYPE db; // db is a single 'digit' after possible padding.
        MANTTYPE cy = 0; // cy is the value of a carry after adding two 'digits'
        int32_t fcompla = 0; // fcompla is a flag to signal a is negative.
        int32_t fcomplb = 0; // fcomplb is a flag to signal b is negative.

        a = pa;

        // Calculate the overlap of the numbers after alignment, this includes
        // necessary padding 0's
        cdigits = Math.Max(a._cdigit + a._exp, b._cdigit + b._exp) - Math.Min(a._exp, b._exp);

        createnum(ref c, (uint32_t)(cdigits + 1));
        c._exp = Math.Min(a._exp, b._exp);
        mexp = c._exp;
        c._cdigit = cdigits;
        pcha = a._mant;
        pchb = b._mant;
        pchc = c._mant;

        // Figure out the sign of the numbers
        if (a._sign != b._sign)
        {
            cy = 1;
            fcompla = (a._sign == -1) ? 1 : 0;
            fcomplb = (b._sign == -1) ? 1 : 0;
        }

        // Loop over all the digits, real and 0 padded. Here we know a and b are
        // aligned
        for (; cdigits > 0; cdigits--, mexp++)
        {
            // Get digit from a, taking padding into account.
            da = (((mexp >= a._exp) && (cdigits + a._exp - c._exp > (c._cdigit - a._cdigit))) ? pcha[pchaCnt++] : 0);
            // Get digit from b, taking padding into account.
            db = (((mexp >= b._exp) && (cdigits + b._exp - c._exp > (c._cdigit - b._cdigit))) ? pchb[pchbCnt++] : 0);

            // Handle complementing for a and b digit. Might be a better way, but
            // haven't found it yet.
            if (fcompla != 0)
            {
                da = (MANTTYPE)(radix) - 1 - da;
            }

            if (fcomplb != 0)
            {
                db = (MANTTYPE)(radix) - 1 - db;
            }

            // Update carry as necessary
            cy = da + db + cy;
            pchc[pchcCnt++] = (MANTTYPE)(cy % (MANTTYPE)radix);
            cy /= (MANTTYPE)radix;
        }

        // Handle carry from last sum as extra digit
        if (cy != 0 && !(fcompla != 0 || fcomplb != 0))
        {
            pchc[pchcCnt++] = cy; // FIXED: Changed from pcha to pchc
            c._cdigit++;
        }

        // Compute sign of result
        if (!(fcompla != 0 || fcomplb != 0))
        {
            c._sign = a._sign;
        }
        else
        {
            if (cy != 0)
            {
                c._sign = 1;
            }
            else
            {
                // In this particular case an overflow or underflow has occurred
                // and all the digits need to be complemented, at one time an
                // attempt to handle this above was made, it turned out to be much
                // slower on average.
                c._sign = -1;
                cy = 1;
                pchcCnt = 0; // Reset counter to start of mantissa

                // FIXED: Properly initialize cdigits to c.cdigit
                for (cdigits = c._cdigit; cdigits > 0; cdigits--)
                {
                    cy = (MANTTYPE)radix - (MANTTYPE)1 - pchc[pchcCnt] + cy;
                    pchc[pchcCnt++] = (MANTTYPE)(cy % (MANTTYPE)radix);
                    cy /= (MANTTYPE)radix;
                }
            }
        }

        // Reset pchcCnt to point to the last digit
        pchcCnt = c._cdigit - 1;

        // Remove leading zeros, remember digits are in order of
        // increasing significance. i.e. 100 would be 0,0,1
        while (c._cdigit > 1 && pchc[pchcCnt--] == 0)
        {
            c._cdigit--;
        }

        pa = c;
    }

    //----------------------------------------------------------------------------
    //
    //    FUNCTION: mulnum
    //
    //    ARGUMENTS: pointer to a number a second number, and the
    //               radix.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the number equivalent of *pa *= b.
    //    Assumes radix is the radix of both numbers.  This algorithm is the
    //    same one you learned in grade school.
    //
    //----------------------------------------------------------------------------

    public static void mulnum(ref PNUMBER pa, PNUMBER b, uint32_t radix)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        if (b._cdigit > 1 || b._mant[0] != 1 || b._exp != 0)
        {
            // If b is one we don't multiply exactly.
            if ((pa)._cdigit > 1 || (pa)._mant[0] != 1 || (pa)._exp != 0)
            {
                // pa and b are both non-one.
                _mulnum(ref pa, b, radix);
            }
            else
            {
                // if pa is one and b isn't just copy b, and adjust the sign.
                int32_t sign = (pa)._sign;
                dupnum(ref pa, b);
                (pa)._sign *= sign;
            }
        }
        else
        {
            // But we do have to set the sign.
            (pa)._sign *= b._sign;
        }
    }

    static void _mulnum(ref PNUMBER pa, PNUMBER b, uint32_t radix)
    {
        PNUMBER? c = null; // c will contain the result.
        PNUMBER? a = null; // a is the dereferenced number pointer from *pa

        MANTTYPE[] pcha; // pcha is a pointer to the mantissa of a.
        MANTTYPE[] pchb; // pchb is a pointer to the mantissa of b.
        // REMOVED: We don't need separate pchc and pchcoffset arrays

        // ADDED: Counters to track position in arrays
        int pchaCnt = 0; // Counter for pcha array position
        int pchbCnt = 0; // Counter for pchb array position
        int pchcCnt = 0; // Counter for current position in result array c._mant
        int pchcoffsetCnt = 0; // Counter for row offset in result array

        int32_t iadigit = 0; // Index of digit being used in the first number.
        int32_t ibdigit = 0; // Index of digit being used in the second number.
        MANTTYPE da = 0; // da is the digit from the fist number.
        TWO_MANTTYPE cy = 0; // cy is the carry resulting from the addition of
        // a multiplied row into the result.
        TWO_MANTTYPE mcy = 0; // mcy is the resultant from a single
        // multiply, AND the carry of that multiply.
        int32_t icdigit = 0; // Index of digit being calculated in final result.

        a = pa;
        ibdigit = a._cdigit + b._cdigit - 1;
        createnum(ref c, (uint32_t)(ibdigit + 1));
        c._cdigit = ibdigit;
        c._sign = a._sign * b._sign;

        c._exp = a._exp + b._exp;
        pcha = a._mant;
        // REMOVED: pchcoffset = c.mant; - We'll use index tracking instead

        for (iadigit = a._cdigit; iadigit > 0; iadigit--)
        {
            da = pcha[pchaCnt++]; // CHANGED: *pcha++ becomes array indexing with counter
            pchb = b._mant;
            pchbCnt = 0; // ADDED: Reset b pointer counter for each digit of a

            // Shift pchc, and pchcoffset, one for each digit
            pchcCnt = pchcoffsetCnt++; // CHANGED: pchc = pchcoffset++ using counters

            for (ibdigit = b._cdigit; ibdigit > 0; ibdigit--)
            {
                cy = 0;
                mcy = (TWO_MANTTYPE)da * pchb[pchbCnt]; // CHANGED: *pchb becomes array indexing
                if (mcy != 0)
                {
                    icdigit = 0;
                    if (ibdigit == 1 && iadigit == 1)
                    {
                        c._cdigit++;
                    }
                }

                // If result is nonzero, or while result of carry is nonzero...
                while (mcy != 0 || cy != 0)
                {
                    // ADDED: Calculate absolute position in c.mant
                    int absPos = pchcCnt + icdigit;

                    // update carry from addition(s) and multiply.
                    cy += (TWO_MANTTYPE)c._mant[absPos] + (mcy % (TWO_MANTTYPE)radix);
                    // CHANGED: pchc[icdigit] becomes c.mant[absPos]

                    // update result digit from
                    c._mant[absPos] = (MANTTYPE)(cy % (TWO_MANTTYPE)radix);
                    // CHANGED: pchc[icdigit++] becomes c.mant[absPos] with separate icdigit++
                    icdigit++;

                    // update carries from
                    mcy /= (TWO_MANTTYPE)radix;
                    cy /= (TWO_MANTTYPE)radix;
                }

                pchbCnt++;
                pchcCnt++; // CHANGED: pchc++ becomes counter increment
            }
        }

        // prevent different kinds of zeros, by stripping leading duplicate zeros.
        // digits are in order of increasing significance.
        while (c._cdigit > 1 && c._mant[c._cdigit - 1] == 0)
        {
            c._cdigit--;
        }

        pa = c;
    }

    //----------------------------------------------------------------------------
    //
    //    FUNCTION: remnum
    //
    //    ARGUMENTS: pointer to a number a second number, and the
    //               radix.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the number equivalent of *pa %= b.
    //            Repeatedly subtracts off powers of 2 of b until *pa < b.
    //
    //
    //----------------------------------------------------------------------------
    static void remnum(ref PNUMBER pa, PNUMBER b, uint32_t radix)
    {
        PNUMBER? tmp = null; // tmp is the working remainder.
        PNUMBER? lasttmp = null; // lasttmp is the last remainder which worked.

        // Once *pa is less than b, *pa is the remainder.
        while (!lessnum(pa, b))
        {
            dupnum(ref tmp, b);
            if (lessnum(tmp, pa))
            {
                // Start off close to the right answer for subtraction.
                tmp._exp = (pa)._cdigit + (pa)._exp - tmp._cdigit;
                if (MSD(pa) <= MSD(tmp))
                {
                    // Don't take the chance that the numbers are equal.
                    tmp._exp--;
                }
            }

            destroynum(ref lasttmp);
            lasttmp = i32tonum(0, radix);

            while (lessnum(tmp, pa))
            {
                dupnum(ref lasttmp, tmp);
                addnum(ref tmp, tmp, radix);
            }

            if (lessnum(pa, tmp))
            {
                // too far, back up...
                destroynum(ref tmp);
                tmp = lasttmp;
                lasttmp = null;
            }

            // Subtract the working remainder from the remainder holder.
            tmp._sign = -1 * (pa)._sign;
            addnum(ref pa, tmp, radix);
            destroynum(ref tmp);
            destroynum(ref lasttmp);
        }
    }

    //---------------------------------------------------------------------------
    //
    //    FUNCTION: divnum
    //
    //    ARGUMENTS: pointer to a number a second number, and the
    //               radix.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the number equivalent of *pa /= b.
    //    Assumes radix is the radix of both numbers.
    //
    //---------------------------------------------------------------------------

    public static void divnum(ref PNUMBER pa, PNUMBER b, uint32_t radix, int32_t precision)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        if (b._cdigit > 1 || b._mant[0] != 1 || b._exp != 0)
        {
            // b is not one
            _divnum(ref pa, b, radix, precision);
        }
        else
        {
            // But we do have to set the sign.
            pa._sign *= b._sign;
        }
    }

    static void _divnum(ref PNUMBER pa, PNUMBER b, uint32_t radix, int32_t precision)
    {
        PNUMBER a = pa;
        int32_t thismax = precision + 2;
        if (thismax < a._cdigit)
        {
            thismax = a._cdigit;
        }

        if (thismax < b._cdigit)
        {
            thismax = b._cdigit;
        }

        PNUMBER? c = null;
        createnum(ref c, (uint32_t)(thismax + 1));
        c._exp = (a._cdigit + a._exp) - (b._cdigit + b._exp) + 1;
        c._sign = a._sign * b._sign;

        MANTTYPE[] ptrc = c._mant;
        int32_t ptrcCnt = thismax;

        PNUMBER? rem = null;
        PNUMBER? tmp = null;
        dupnum(ref rem, a);
        dupnum(ref tmp, b);
        tmp._sign = a._sign;
        rem._exp = b._cdigit + b._exp - rem._cdigit;

        // Build a table of multiplications of the divisor, this is quicker for
        // more than radix 'digits'
        LinkedList<PNUMBER> numberList = new LinkedList<PNUMBER>();
        numberList.AddFirst(i32tonum(0, radix));

        for (uint32_t i = 1; i < radix; i++)
        {
            PNUMBER? newValue = null;
            dupnum(ref newValue, numberList.First!.Value);
            addnum(ref newValue, tmp, radix);

            numberList.AddFirst(newValue);
        }

        destroynum(ref tmp);

        int32_t digit;
        int32_t cdigits = 0;
        while (cdigits++ < thismax && !zernum(rem))
        {
            digit = (int32_t)(radix - 1);
            PNUMBER? multiple = null;
            foreach (var num in numberList)
            {
                if (!lessnum(rem, num) || --digit == 0)
                {
                    multiple = num;
                    break;
                }
            }

            if (digit != 0)
            {
                multiple!._sign *= -1;
                addnum(ref rem, multiple, radix);
                multiple._sign *= -1;
            }

            rem._exp++;
            ptrc[ptrcCnt--] = (MANTTYPE)digit;
        }

        cdigits--;

        // This is equivalent to "if (c->mant != ++ptrc)" in C++
        if (ptrcCnt + 1 > 0) // If we need to shift the data
        {
            // Move the digits to the beginning of the array
            Array.Copy(ptrc, ptrcCnt + 1, ptrc, 0, cdigits);
        }

        // Cleanup table structure
        numberList.Clear();

        if (cdigits == 0)
        {
            c._cdigit = 1;
            c._exp = 0;
        }
        else
        {
            c._cdigit = cdigits;
            c._exp -= cdigits;
            while (c._cdigit > 1 && c._mant[c._cdigit - 1] == 0)
            {
                c._cdigit--;
            }
        }

        destroynum(ref rem);
        pa = c;
    }

    //---------------------------------------------------------------------------
    //
    //    FUNCTION: equnum
    //
    //    ARGUMENTS: two numbers.
    //
    //    RETURN: Boolean
    //
    //    DESCRIPTION: Does the number equivalent of ( a == b )
    //    Only assumes that a and b are the same radix.
    //
    //---------------------------------------------------------------------------

    public static bool equnum(PNUMBER a, PNUMBER b)
    {
        if (a is null)
        {
            throw new ArgumentNullException(nameof(a));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        int32_t diff;
        MANTTYPE[] pa;
        MANTTYPE[] pb;
        int32_t cdigits;
        int32_t ccdigits;
        MANTTYPE da;
        MANTTYPE db;

        diff = (a._cdigit + a._exp) - (b._cdigit + b._exp);
        if (diff < 0)
        {
            // If the exponents are different, these are different numbers.
            return false;
        }
        else
        {
            if (diff > 0)
            {
                // If the exponents are different, these are different numbers.
                return false;
            }
            else
            {
                // OK the exponents match.
                pa = a._mant;
                pb = b._mant;
                var paCnt = a._cdigit - 1;
                var pbCnt = b._cdigit - 1;
                cdigits = Math.Max(a._cdigit, b._cdigit);
                ccdigits = cdigits;

                // Loop over all digits until we run out of digits or there is a
                // difference in the digits.
                for (; cdigits > 0; cdigits--)
                {
                    da = ((cdigits > (ccdigits - a._cdigit)) ? pa[paCnt--] : 0);
                    db = ((cdigits > (ccdigits - b._cdigit)) ? pb[pbCnt--] : 0);
                    if (da != db)
                    {
                        return false;
                    }
                }

                // In this case, they are equal.
                return true;
            }
        }
    }

    //---------------------------------------------------------------------------
    //
    //    FUNCTION: lessnum
    //
    //    ARGUMENTS: two numbers.
    //
    //    RETURN: Boolean
    //
    //    DESCRIPTION: Does the number equivalent of ( abs(a) < abs(b) )
    //    Only assumes that a and b are the same radix, WARNING THIS IS AN.
    //    UNSIGNED COMPARE!
    //
    //---------------------------------------------------------------------------
    static bool lessnum(PNUMBER a, PNUMBER b)
    {
        int32_t diff = (a._cdigit + a._exp) - (b._cdigit + b._exp);
        if (diff < 0)
        {
            // The exponent of a is less than b
            return true;
        }

        if (diff > 0)
        {
            return false;
        }

        MANTTYPE[] pa = a._mant;
        MANTTYPE[] pb = b._mant;

        int paCnt = a._cdigit - 1;
        int pbCnt = b._cdigit - 1;

        int32_t cdigits = Math.Max(a._cdigit, b._cdigit);
        int32_t ccdigits = cdigits;
        for (; cdigits > 0; cdigits--)
        {
            // PORT: FIX: Apply post-decrement to the array index, not the value
            MANTTYPE da = ((cdigits > (ccdigits - a._cdigit)) ? pa[paCnt--] : 0);
            MANTTYPE db = ((cdigits > (ccdigits - b._cdigit)) ? pb[pbCnt--] : 0);
            diff = (int32_t)(da - db);
            if (diff != 0)
            {
                return (diff < 0);
            }
        }

        // In this case, they are equal.
        return false;
    }

    //----------------------------------------------------------------------------
    //
    //    FUNCTION: zernum
    //
    //    ARGUMENTS: number
    //
    //    RETURN: Boolean
    //
    //    DESCRIPTION: Does the number equivalent of ( !a )
    //
    //----------------------------------------------------------------------------
    public static bool zernum(PNUMBER a)
    {
        if (a is null)
        {
            throw new ArgumentNullException(nameof(a));
        }

        int32_t length;
        MANTTYPE[] pcha;
        int32_t pchaCnt = 0;
        length = a._cdigit;
        pcha = a._mant;

        // loop over all the digits until you find a nonzero or until you run
        // out of digits
        while (length-- > 0)
        {
            if (pcha[pchaCnt++] != 0)
            {
                // One of the digits isn't zero, therefore the number isn't zero
                return false;
            }
        }

        // All of the digits are zero, therefore the number is zero
        return true;
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: gcdrat
    //
    //    ARGUMENTS: pointer to a rational.
    //
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Divides p and q in rational by the G.C.D.
    //    of both.  It was hoped this would speed up some
    //    calculations, and until the above trimming was done it
    //    did, but after trimming gcdratting, only slows things
    //    down.
    //
    //-----------------------------------------------------------------------------
    public void gcdrat(ref PRAT pa, int32_t precision)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        PNUMBER? pgcd = null;
        PRAT? a = null;

        a = pa;
        pgcd = gcd(a._pp, a._pq);

        if (!zernum(pgcd))
        {
            divnumx(ref (a._pp), pgcd, precision);
            divnumx(ref (a._pq), pgcd, precision);
        }

        destroynum(ref pgcd);
        pa = a;

        RENORMALIZE(pa);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: fracrat
    //
    //    ARGUMENTS: pointer to a rational a second rational.
    //
    //    RETURN: None, changes pointer.
    //
    //    DESCRIPTION: Does the rational equivalent of frac(*pa);
    //
    //-----------------------------------------------------------------------------
    public void fracrat(ref PRAT pa, uint32_t radix, int32_t precision)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        // Only do the flatrat operation if number is nonzero.
        // and only if the bottom part is not one.
        if (!zernum((pa)._pp) && !equnum(pa._pq, num_one))
        {
            flatrat(ref pa, radix, precision);
        }

        remnum(ref ((pa)._pp), (pa)._pq, BASEX);

        // Get *pa back in the integer over integer form.
        RENORMALIZE(pa);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: mulrat
    //
    //    ARGUMENTS: pointer to a rational a second rational.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the rational equivalent of *pa *= b.
    //    Assumes radix is the radix of both numbers.
    //
    //-----------------------------------------------------------------------------
    public void mulrat(ref PRAT pa, PRAT b, int32_t precision)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        // Only do the multiply if it isn't zero.
        if (!zernum((pa)._pp))
        {
            mulnumx(ref ((pa)._pp), b._pp);
            mulnumx(ref ((pa)._pq), b._pq);
            trimit(ref pa, precision);
        }
        else
        {
            // If it is zero, blast a one in the denominator.
            dupnum(ref ((pa)._pq), num_one);
        }

#if MULGCD
        gcdrat(pa);
#endif
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: divrat
    //
    //    ARGUMENTS: pointer to a rational a second rational.
    //
    //    RETURN: None, changes first pointer.
    //
    //    DESCRIPTION: Does the rational equivalent of *pa /= b.
    //    Assumes radix is the radix of both numbers.
    //
    //-----------------------------------------------------------------------------
    public void divrat(ref PRAT pa, PRAT b, int32_t precision)
    {
        if (pa is null)
        {
            throw new ArgumentNullException(nameof(pa));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        if (!zernum((pa)._pp))
        {
            // Only do the divide if the top isn't zero.
            mulnumx(ref ((pa)._pp), b._pq);
            mulnumx(ref ((pa)._pq), b._pp);

            if (zernum((pa)._pq))
            {
                // raise an exception if the bottom is 0.
                throw new CalcErrException(CalcErr.DivideByZero);
            }

            trimit(ref pa, precision);
        }
        else
        {
            // Top is zero.
            if (zerrat(b))
            {
                // If bottom is zero
                // 0 / 0 is indefinite, raise an exception.
                throw new CalcErrException(CalcErr.Indefinite);
            }
            else
            {
                // 0/x make a unique 0.
                dupnum(ref ((pa)._pq), num_one);
            }
        }

#if DIVGCD
        gcdrat(pa);
#endif
    }

