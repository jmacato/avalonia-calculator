    // RENORMALIZE, gets the exponents non-negative.
    private static void RENORMALIZE(PRAT x)
    {
        if (x._pp._exp < 0)
        {
            x._pq._exp -= x._pp._exp;
            x._pp._exp = 0;
        }

        if (x._pq._exp < 0)
        {
            x._pp._exp -= x._pq._exp;
            x._pq._exp = 0;
        }
    }

    // TRIMNUM ASSUMES the number is in radix form NOT INTERNAL BASEX!!!
    private void TRIMNUM(NUMBER x, int32_t precision)
    {
        if (!g_ftrueinfinite)
        {
            int32_t trim = x._cdigit - precision - g_ratio;
            if (trim > 1)
            {

                // Replace memmove with Array.Copy to shift elements within the array
                // This moves elements starting at index 'trim' to the beginning of the array
                Array.Copy(x._mant, trim, x._mant, 0, x._cdigit - trim);

                x._cdigit -= trim;
                x._exp += trim;
            }
        }
    }

    // TRIMTOP ASSUMES the number is in INTERNAL BASEX!!!
    private void TRIMTOP(PRAT x, int32_t precision)
    {
        if (!g_ftrueinfinite)
        {
            int32_t trim = x._pp._cdigit - precision / g_ratio - 2;
            if (trim > 1)
            {
                Array.Copy(x._pp._mant, trim, x._pp._mant, 0, x._pp._cdigit - trim);
                x._pp._cdigit -= trim;
                x._pp._exp += trim;
            }

            trim = Math.Min(x._pp._exp, x._pq._exp);
            x._pp._exp -= trim;
            x._pq._exp -= trim;
        }
    }

    private bool SMALL_ENOUGH_RAT(PRAT a, int32_t precision)
    {
        return zernum(a._pp) ||
               (a._pq._cdigit + a._pq._exp - (a._pp._cdigit + a._pp._exp) - 1) * g_ratio > precision;
    }

