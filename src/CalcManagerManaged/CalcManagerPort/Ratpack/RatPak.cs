    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: i32tonum
    //
    //    ARGUMENTS: int32_t input and radix requested.
    //
    //    RETURN: number
    //
    //    DESCRIPTION: Returns a number representation in the
    //    base   requested of the int32_t value passed in.
    //
    //-----------------------------------------------------------------------------
    public static PNUMBER i32tonum(int32_t ini32, uint32_t radix)
    {
        MANTTYPE[] pmant;
        uint32_t pmantCnt = 0;
        PNUMBER? pnumret = null;
        createnum(ref pnumret, MAX_LONG_SIZE);
        pmant = pnumret._mant;
        pnumret._cdigit = 0;
        pnumret._exp = 0;
        if (ini32 < 0)
        {
            pnumret._sign = -1;
            //        ini32 *= -1;  // PORTFIX1 ISSUE: This will fail for INT_MIN
        }
        else
        {
            pnumret._sign = 1;
        }

        // PORTFIX1: Get absolute value safely using long to avoid overflow.
        // Gotta watch out for differences in overflow handling in C# and C++.
        // C# just wraps around to max while C++ discards the overflown bits.
        uint32_t value = (uint32_t)(ini32 < 0 ? -((long)ini32) : ini32);
        do
        {
            pmant[pmantCnt++] = (value % radix);
            value /= radix;
            pnumret._cdigit++;
        } while (value != 0);

        return (pnumret);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: Ui32tonum
    //
    //    ARGUMENTS: uint32_t input and radix requested.
    //
    //    RETURN: number
    //
    //    DESCRIPTION: Returns a number representation in the
    //    base   requested of the uint32_t value passed in. Being unsigned number it has no
    //    negative number and takes the full range of unsigned number
    //
    //-----------------------------------------------------------------------------
    public static PNUMBER Ui32tonum(uint32_t ini32, uint32_t radix)
    {
        MANTTYPE[] pmant;
        var pmantCnt = 0;
        PNUMBER? pnumret = null;
        createnum(ref pnumret, MAX_LONG_SIZE);
        pmant = pnumret._mant;
        pnumret._cdigit = 0;
        pnumret._exp = 0;
        pnumret._sign = 1;
        do
        {
            pmant[pmantCnt++] = (MANTTYPE)(ini32 % radix);
            ini32 /= radix;
            pnumret._cdigit++;
        } while (ini32 != 0);

        return (pnumret);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: rattoi32
    //
    //    ARGUMENTS: rational number in internal base, integer radix and int32_t precision.
    //
    //    RETURN: int32_t
    //
    //    DESCRIPTION: returns the int32_t representation of the
    //    number input.  Assumes that the number is in the internal
    //    base.
    //
    //-----------------------------------------------------------------------------

    public int32_t rattoi32(PRAT prat, uint32_t radix, int32_t precision)
    {
        if (RatGt(prat, rat_max_i32, precision) || RatLt(prat, rat_min_i32, precision))
        {
            // Don't attempt rattoi32 of anything too big or small
            throw new CalcErrException(CalcErr.Domain);
        }

        PRAT? pint = null;
        duprat(ref pint, prat);

        intrat(ref pint, radix, precision);
        divnumx(ref (pint._pp), pint._pq, precision);
        dupnum(ref pint._pq, num_one);

        int32_t lret = numtoi32(pint._pp, BASEX);

        destroyrat(ref pint);

        return (lret);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: rattoUi32
    //
    //    ARGUMENTS: rational number in internal base, integer radix and int32_t precision.
    //
    //    RETURN: Ui32
    //
    //    DESCRIPTION: returns the Ui32 representation of the
    //    number input.  Assumes that the number is in the internal
    //    base.
    //
    //-----------------------------------------------------------------------------
    public uint32_t rattoUi32(PRAT prat, uint32_t radix, int32_t precision)
    {
        if (RatGt(prat, rat_dword, precision) || RatLt(prat, rat_zero, precision))
        {
            // Don't attempt rattoui32 of anything too big or small
            throw new CalcErrException(CalcErr.Domain);
        }

        PRAT? pint = null;
        duprat(ref pint, prat);

        intrat(ref pint, radix, precision);
        divnumx(ref (pint._pp), pint._pq, precision);
        dupnum(ref pint._pq, num_one);

        // uint32_t lret = (uint32_t)numtoi32(pint.pp, BASEX); // This happens to work even if it is only signed
        int32_t signedResult = numtoi32(pint._pp, BASEX);
        uint32_t lret = (uint32_t)signedResult;

        destroyrat(ref pint);

        return (lret);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: rattoUi64
    //
    //    ARGUMENTS: rational number in internal base, integer radix and int32_t precision
    //
    //    RETURN: Ui64
    //
    //    DESCRIPTION: returns the 64 bit (irrespective of which processor this is running in) representation of the
    //    number input.  Assumes that the number is in the internal
    //    base. Can throw exception if the number exceeds 2^64
    //    Implementation by getting the HI & LO 32 bit words and concatenating them, as the
    //    internal base chosen happens to be 2^32, this is easier.
    //-----------------------------------------------------------------------------
    public uint64_t rattoUi64(PRAT prat, uint32_t radix, int32_t precision)
    {
        PRAT? pint = null;

        // first get the LO 32 bit word
        duprat(ref pint, prat);
        andrat(ref pint, rat_dword, radix, precision); // & 0xFFFFFFFF   (2 ^ 32 -1)
        uint32_t lo = rattoUi32(pint, radix, precision); // wont throw exception because already hi-dword chopped off

        duprat(ref pint, prat); // previous pint will get freed by this as well
        PRAT? prat32 = i32torat(32);
        rshrat(ref pint, prat32, radix, precision);
        intrat(ref pint, radix, precision);
        andrat(ref pint, rat_dword, radix, precision); // & 0xFFFFFFFF   (2 ^ 32 -1)
        uint32_t hi = rattoUi32(pint, radix, precision);

        destroyrat(ref prat32);
        destroyrat(ref pint);

        return (((uint64_t)hi << 32) | lo);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: numtoi32
    //
    //    ARGUMENTS: number input and base of that number.
    //
    //    RETURN: int32_t
    //
    //    DESCRIPTION: returns the int32_t representation of the
    //    number input.  Assumes that the number is really in the
    //    base   claimed.
    //
    //-----------------------------------------------------------------------------
    public static int32_t numtoi32(PNUMBER pnum, uint32_t radix)
    {
        if (pnum is null)
        {
            throw new ArgumentNullException(nameof(pnum));
        }

        long lret = 0;

        MANTTYPE[] pmant = pnum._mant;
        var pmantCnt = pnum._cdigit - 1;

        int32_t expt = pnum._exp;
        for (int32_t length = pnum._cdigit; length > 0 && length + expt > 0; length--)
        {
            lret = (int32_t)(lret * radix);
            lret = (int32_t)(lret + (pmant[pmantCnt--]));
        }

        while (expt-- > 0)
        {
            lret = (int32_t)(lret * radix);
        }

        lret *= pnum._sign;

        return (int32_t)lret;
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: bool stripzeroesnum
    //
    //    ARGUMENTS:            a number representation
    //
    //    RETURN: true if stripping done, modifies number in place.
    //
    //    DESCRIPTION: Strips off trailing zeros.
    //
    //-----------------------------------------------------------------------------
    public static bool stripzeroesnum(ref PNUMBER pnum, int32_t starting)
    {
        if (pnum is null)
        {
            throw new ArgumentNullException(nameof(pnum));
        }

        bool fstrip = false;
        // point pmant to the LeastCalculatedDigit
        MANTTYPE[] pmant = pnum._mant;
        var pmantCnt = 0;

        int32_t cdigits = pnum._cdigit;
        // point pmant to the LSD
        if (cdigits > starting)
        {
            pmantCnt += cdigits - starting;
            cdigits = starting;
        }

        // Check we haven't gone too far, and we are still looking at zeros.
        while ((cdigits > 0) && pmant[pmantCnt] == 0)
        {
            // move to next significant digit and keep track of digits we can
            // ignore later.
            pmantCnt++;
            cdigits--;
            fstrip = true;
        }

        // If there are zeros to remove.
        if (fstrip)
        {
            // Remove them.
            Array.Copy(pnum._mant, pmantCnt, pnum._mant, 0, cdigits);

            // And adjust exponent and digit count accordingly.
            pnum._exp += (pnum._cdigit - cdigits);
            pnum._cdigit = cdigits;
        }

        return (fstrip);
    }

    private PNUMBER? NumberToStringMakeRound(PNUMBER pnum, NumberFormat format, uint32_t radix, int32_t precision, int32_t exponent, ref int32_t length)
    {
        PNUMBER? round = null;
        if (!zernum(pnum) && (pnum._cdigit >= precision ||
                              (length - exponent > precision && exponent >= -MAX_ZEROS_AFTER_DECIMAL)))
        {
            // Otherwise round.
            round = i32tonum((int32_t)radix, radix);
            divnum(ref round, num_two, radix, precision);

            // Make round number exponent one below the LSD for the number.
            if (exponent > 0 || format == NumberFormat.FloatingPoint)
            {
                round._exp = pnum._exp + pnum._cdigit - round._cdigit - precision;
            }
            else
            {
                round._exp = pnum._exp + pnum._cdigit - round._cdigit - precision - exponent;
                length = precision + exponent;
            }

            round._sign = pnum._sign;
        }

        return round;
    }

    static void NumberToStringAdjustForFloatingPoint(ref NumberFormat format, PNUMBER? round, int32_t precision, int32_t exponent, ref int32_t length)
    {
        if (format == NumberFormat.FloatingPoint)
        {
            // Figure out if the exponent will fill more space than the non-exponent field.
            if ((length - exponent > precision) || (exponent > precision + 3))
            {
                if (exponent >= -MAX_ZEROS_AFTER_DECIMAL)
                {
                    round!._exp -= exponent;
                    length = precision + exponent;
                }
                else
                {
                    // Case where too many zeros are to the right or left of the
                    // decimal pt. And we are forced to switch to scientific form.
                    format = NumberFormat.Scientific;
                }
            }
            else if (length + Math.Abs(exponent) < precision && round != null)
            {
                // Minimum loss of precision occurs with listing leading zeros
                // if we need to make room for zeros sacrifice some digits.
                round._exp -= exponent;
            }
        }
    }

    static bool NumberToStringSetupSciForm(NumberFormat format, ref int32_t exponent, ref int32_t eout)
    {
        bool useSciForm = false;

        // Case where too many digits are to the left of the decimal or
        // NumberFormat.Scientific or NumberFormat.Engineering was specified.
        if ((format == NumberFormat.Scientific) || (format == NumberFormat.Engineering))
        {
            useSciForm = true;
            if (eout != 0)
            {
                if (format == NumberFormat.Engineering)
                {
                    exponent = (eout % 3);
                    eout -= exponent;
                    exponent++;

                    // Fix the case where 0.02e-3 should really be 2.e-6 etc.
                    if (exponent < 0)
                    {
                        exponent += 3;
                        eout -= 3;
                    }
                }
                else
                {
                    exponent = 1;
                }
            }
        }
        else
        {
            eout = 0;
        }

        return useSciForm;
    }

    private wstring NumberToStringBuildResult(PNUMBER pnum, uint32_t radix, int32_t length, int32_t exponent, int32_t eout, bool useSciForm)
    {
        MANTTYPE[] pmant = pnum._mant;
        var pmantCnt = pnum._cdigit - 1;

        // Begin building the result string
        StringBuilder result = new();

        // Make sure negative zeros aren't allowed.
        if ((pnum._sign == -1) && (length > 0))
        {
            result.Append('-');
        }

        if (exponent <= 0 && !useSciForm)
        {
            result.Append('0');
            result.Append(g_decimalSeparator);
            // Used up a digit unaccounted for.
        }

        while (exponent < 0)
        {
            result.Append('0');
            exponent++;
        }

        while (length > 0)
        {
            exponent--;
            result.Append(DIGITS[(int)pmant[pmantCnt--]]);
            length--;

            // Be more regular in using a decimal point.
            if (exponent == 0)
            {
                result.Append(g_decimalSeparator);
            }
        }

        while (exponent > 0)
        {
            result.Append('0');
            exponent--;
            // Be more regular in using a decimal point.
            if (exponent == 0)
            {
                result.Append(g_decimalSeparator);
            }
        }

        if (useSciForm)
        {
            result.Append(radix == 10 ? 'e' : '^');
            result.Append(eout < 0 ? '-' : '+');
            eout = Math.Abs(eout);
            StringBuilder expString = new();
            do
            {
                // This is to emulate the reversed insert that expString.crbegin() does.
                // reference: https://en.cppreference.com/w/cpp/string/basic_string/rbegin
                expString.Insert(0, DIGITS[(int)(eout % radix)]);
                eout = (int32_t)(eout / radix);
            } while (eout > 0);

            result.Append(expString);
            // This got emulated on the above do-while.
        }

        // Remove trailing decimal
        if (result.Length != 0 && result[result.Length - 1] == g_decimalSeparator)
        {
            result.Remove(result.Length - 1, 1);
        }

        return result.ToString();
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: NumberToString
    //
    //    ARGUMENTS: number representation
    //          fmt, one of NumberFormat.FloatingPoint, NumberFormat.Scientific or
    //          NumberFormat.Engineering
    //          integer radix and int32_t precision value
    //
    //    RETURN: String representation of number.
    //
    //    DESCRIPTION: Converts a number to its string
    //    representation.
    //
    //-----------------------------------------------------------------------------
    public wstring NumberToString(ref PNUMBER pnum, NumberFormat format, uint32_t radix, int32_t precision)
    {
        if (pnum is null)
        {
            throw new ArgumentNullException(nameof(pnum));
        }

        stripzeroesnum(ref pnum, precision + 2);
        int32_t length = pnum._cdigit;
        int32_t exponent = pnum._exp + length; // Actual number of digits to the left of decimal

        NumberFormat oldFormat = format;
        if (exponent > precision && format == NumberFormat.FloatingPoint)
        {
            // Force scientific mode to prevent user from assuming 33rd digit is exact.
            format = NumberFormat.Scientific;
        }

        // Make length small enough to fit in pret.
        if (length > precision)
        {
            length = precision;
        }

        // If there is a chance a round has to occur, round.
        // - if number is zero no rounding
        // - if number of digits is less than the maximum output no rounding
        PNUMBER? round = NumberToStringMakeRound(pnum, format, radix, precision, exponent, ref length);

        NumberToStringAdjustForFloatingPoint(ref format, round, precision, exponent, ref length);

        if (round != null)
        {
            addnum(ref pnum, round, radix);
            int32_t offset = (pnum._cdigit + pnum._exp) - (round._cdigit + round._exp);
            destroynum(ref round);
            if (stripzeroesnum(ref pnum, offset))
            {
                // WARNING: nesting/recursion, too much has been changed, need to
                // re-figure format.
                return NumberToString(ref pnum, oldFormat, radix, precision);
            }
        }
        else
        {
            stripzeroesnum(ref pnum, precision);
        }

        // Set up all the post rounding stuff.
        int32_t eout = exponent - 1; // Displayed exponent.
        bool useSciForm = NumberToStringSetupSciForm(format, ref exponent, ref eout);

        return NumberToStringBuildResult(pnum, radix, length, exponent, eout, useSciForm);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: RatToString
    //
    //  ARGUMENTS:
    //              PRAT *representation of a number.
    //              i32 representation of base  to  dump to screen.
    //              fmt, one of NumberFormat.FloatingPoint, NumberFormat.Scientific, or NumberFormat.Engineering
    //              precision uint32_t
    //
    //  RETURN: string
    //
    //  DESCRIPTION: returns a string representation of rational number passed
    //  in, at least to the precision digits.
    //
    //  NOTE: It may be that doing a GCD() could shorten the rational form
    //       And it may eventually be worthwhile to keep the result.  That is
    //       why a pointer to the rational is passed in.
    //
    //-----------------------------------------------------------------------------
    public wstring RatToString(ref PRAT prat, NumberFormat format, uint32_t radix, int32_t precision)
    {
        PNUMBER? p = RatToNumber(prat, radix, precision);

        wstring result = NumberToString(ref p, format, radix, precision);
        destroynum(ref p);

        return result;
    }

    public PNUMBER RatToNumber(PRAT prat, uint32_t radix, int32_t precision)
    {
        PRAT? temprat = null;
        duprat(ref temprat, prat);
        // Convert p and q of rational form from internal base to requested base.
        // Scale by largest power of BASEX possible.
        int32_t scaleby = Math.Min(temprat._pp._exp, temprat._pq._exp);
        scaleby = Math.Max(scaleby, 0);

        temprat._pp._exp -= scaleby;
        temprat._pq._exp -= scaleby;

        PNUMBER p = nRadixxtonum(temprat._pp, radix, precision);
        PNUMBER? q = nRadixxtonum(temprat._pq, radix, precision);

        destroyrat(ref temprat);

        // finally take the time hit to actually divide.
        divnum(ref p, q, radix, precision);
        destroynum(ref q);

        return p;
    }

    // Converts a PRAT to a PNUMBER and back to a PRAT, flattening/simplifying the rational in the process
    public void flatrat(ref PRAT prat, uint32_t radix, int32_t precision)
    {
        PNUMBER? pnum = RatToNumber(prat, radix, precision);
        prat = numtorat(pnum, radix);
        destroynum(ref pnum);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: gcd
    //
    //  ARGUMENTS:
    //              PNUMBER representation of a number.
    //              PNUMBER representation of a number.
    //              int for Radix
    //
    //  RETURN: Greatest common divisor in internal BASEX PNUMBER form.
    //
    //  DESCRIPTION: gcd uses remainders to find the greatest common divisor.
    //
    //  ASSUMPTIONS: gcd assumes inputs are integers.
    //
    //  NOTE: Before it was found that the TRIM macro actually kept the
    //        size down cheaper than GCD, this routine was used extensively.
    //        now it is not used but might be later.
    //
    //-----------------------------------------------------------------------------

    public static PNUMBER gcd(PNUMBER a, PNUMBER b)
    {
        if (a is null)
        {
            throw new ArgumentNullException(nameof(a));
        }

        if (b is null)
        {
            throw new ArgumentNullException(nameof(b));
        }

        PNUMBER? r = null;
        PNUMBER? larger = null;
        PNUMBER? smaller = null;

        if (zernum(a))
        {
            return b;
        }
        else if (zernum(b))
        {
            return a;
        }

        if (lessnum(a, b))
        {
            dupnum(ref larger, b);
            dupnum(ref smaller, a);
        }
        else
        {
            dupnum(ref larger, a);
            dupnum(ref smaller, b);
        }

        while (!zernum(smaller))
        {
            remnum(ref larger, smaller, BASEX);
            // swap larger and smaller
            r = larger;
            larger = smaller;
            smaller = r;
        }

        destroynum(ref smaller);
        return larger;
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: i32factnum
    //
    //  ARGUMENTS:
    //              int32_t integer to factorialize.
    //              int32_t integer representing base   of answer.
    //              uint32_t integer for radix
    //
    //  RETURN: Factorial of input in radix PNUMBER form.
    //
    //  NOTE:  Not currently used.
    //
    //-----------------------------------------------------------------------------
    public static PNUMBER i32factnum(int32_t ini32, uint32_t radix)
    {
        PNUMBER? lret = null;
        PNUMBER? tmp = null;

        lret = i32tonum(1, radix);

        while (ini32 > 0)
        {
            tmp = i32tonum(ini32--, radix);
            mulnum(ref lret, tmp, radix);
            destroynum(ref tmp);
        }

        return (lret);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: i32prodnum
    //
    //  ARGUMENTS:
    //              int32_t integer to factorialize.
    //              int32_t integer representing base of answer.
    //              uint32_t integer for radix
    //
    //  RETURN: Factorial of input in base PNUMBER form.
    //
    //-----------------------------------------------------------------------------
    public static PNUMBER i32prodnum(int32_t start, int32_t stop, uint32_t radix)
    {
        PNUMBER? lret = null;
        PNUMBER? tmp = null;

        lret = i32tonum(1, radix);

        while (start <= stop)
        {
            if (start != 0)
            {
                tmp = i32tonum(start, radix);
                mulnum(ref lret, tmp, radix);
                destroynum(ref tmp);
            }

            start++;
        }

        return (lret);
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: numpowi32
    //
    //    ARGUMENTS: root as number power as int32_t and radix of
    //               number along with the precision value in int32_t.
    //
    //    RETURN: None root is changed.
    //
    //    DESCRIPTION: changes numeric representation of root to
    //    root ** power. Assumes radix is the radix of root.
    //
    //-----------------------------------------------------------------------------
    public void numpowi32(ref PNUMBER proot, int32_t power, uint32_t radix, int32_t precision)
    {
        if (proot is null)
        {
            throw new ArgumentNullException(nameof(proot));
        }

        PNUMBER lret = i32tonum(1, radix);

        while (power > 0)
        {
            if ((power & 1) != 0)
            {
                mulnum(ref lret, proot, radix);
            }

            mulnum(ref proot, proot, radix);
            TRIMNUM(proot, precision);
            power >>= 1;
        }

        proot = lret;
    }

    //-----------------------------------------------------------------------------
    //
    //    FUNCTION: ratpowi32
    //
    //    ARGUMENTS: root as rational, power as int32_t and precision as int32_t.
    //
    //    RETURN: None root is changed.
    //
    //    DESCRIPTION: changes rational representation of root to
    //    root ** power.
    //
    //-----------------------------------------------------------------------------
    public void ratpowi32(ref PRAT proot, int32_t power, int32_t precision)
    {
        if (proot is null)
        {
            throw new ArgumentNullException(nameof(proot));
        }

        if (power < 0)
        {
            // Take the positive power and invert answer.
            PNUMBER? pnumtemp = null;
            ratpowi32(ref proot, -power, precision);
            pnumtemp = (proot)._pp;
            (proot)._pp = (proot)._pq;
            (proot)._pq = pnumtemp;
        }
        else
        {
            PRAT? lret = null;

            lret = i32torat(1);

            while (power > 0)
            {
                if ((power & 1) != 0)
                {
                    mulnumx(ref (lret._pp), (proot)._pp);
                    mulnumx(ref (lret._pq), (proot)._pq);
                }

                mulrat(ref proot, proot, precision);
                trimit(ref lret, precision);
                trimit(ref proot, precision);
                power >>= 1;
            }

            proot = lret;
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: exprat
    //
    //  ARGUMENTS: x PRAT representation of number to exponentiate
    //
    //  RETURN: exp  of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___
    //   \  ]                                               X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j      j+1
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //-----------------------------------------------------------------------------

    void _exprat(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        addnum(ref (pret._pp), num_one, BASEX);
        addnum(ref (pret._pq), num_one, BASEX);
        duprat(ref thisterm, pret);

        n2 = i32tonum(0, BASEX);

        do
        {
            EXP_RAT_NEXTTERM(ref thisterm, ref px, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void exprat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT? pwr = null;
        PRAT? pint = null;

        if (RatGt(px, rat_max_exp, precision) || RatLt(px, rat_min_exp, precision))
        {
            // Don't attempt exp of anything large.
            throw new CalcErrException(CalcErr.Domain);
        }

        duprat(ref pwr, rat_exp);
        duprat(ref pint, px);

        intrat(ref pint, radix, precision);

        int32_t intpwr = rattoi32(pint, radix, precision);
        ratpowi32(ref pwr, intpwr, precision);

        subrat(ref px, pint, precision);

        // It just so happens to be an integral power of e.
        if (RatGt(px, rat_negsmallest, precision) && RatLt(px, rat_smallest, precision))
        {
            duprat(ref px, pwr);
        }
        else
        {
            _exprat(ref px, precision);
            mulrat(ref px, pwr, precision);
        }

        destroyrat(ref pwr);
        destroyrat(ref pint);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: lograt, _lograt
    //
    //  ARGUMENTS: x PRAT representation of number to logarithim
    //
    //  RETURN: log  of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___
    //   \  ]                                             j*(1-X)
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j      j+1
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   Number is scaled between one and e_to_one_half prior to taking the
    //   log. This is to keep execution time from exploding.
    //
    //
    //-----------------------------------------------------------------------------

    void _lograt(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        createrat(ref thisterm);

        // sub one from x
        (px)._pq._sign *= -1;
        addnum(ref ((px)._pp), (px)._pq, BASEX);
        (px)._pq._sign *= -1;

        duprat(ref pret, px);
        duprat(ref thisterm, px);

        n2 = i32tonum(1, BASEX);
        (px)._pp._sign *= -1;

        do
        {
            LOG_RAT_NEXTTERM(ref thisterm, ref px, ref n2, precision, ref pret);
            TRIMTOP(px, precision);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void lograt(ref PRAT px, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        PRAT? pwr = null; // pwr is the large scaling factor.
        PRAT? offset = null; // offset is the incremental scaling factor.

        // Check for someone taking the log of zero or a negative number.
        if (rat_le(px, rat_zero, precision))
        {
            throw new CalcErrException(CalcErr.Domain);
        }

        // Get number > 1, for scaling
        bool fneglog = RatLt(px, rat_one, precision);
        if (fneglog)
        {
            PNUMBER pnumtemp = (px)._pp;
            (px)._pp = (px)._pq;
            (px)._pq = pnumtemp;
        }

        // Scale the number within BASEX factor of 1, for the large scale.
        // log(x*2^(BASEXPWR*k)) = BASEXPWR*k*log(2)+log(x)
        if (LOGRAT2(px) > 1)
        {
            int32_t intpwr = LOGRAT2(px) - 1;
            (px)._pq._exp += intpwr;
            pwr = i32torat(unchecked((int32_t)(intpwr * BASEXPWR))); // TODO: Check this for overflowhandling
            mulrat(ref pwr, ln_two, precision);
            // ln(x+e)-ln(x) looks close to e when x is close to one using some
            // expansions.  This means we can trim past precision digits+1.
            TRIMTOP(px, precision);
        }
        else
        {
            duprat(ref pwr, rat_zero);
        }

        duprat(ref offset, rat_zero);
        // Scale the number between 1 and e_to_one_half, for the small scale.
        while (RatGt(px, e_to_one_half, precision))
        {
            divrat(ref px, e_to_one_half, precision);
            addrat(ref offset, rat_one, precision);
        }

        _lograt(ref px, precision);

        // Add the large and small scaling factors, take into account
        // small scaling was done in e_to_one_half chunks.
        divrat(ref offset, rat_two, precision);
        addrat(ref pwr, offset, precision);

        // And add the resulting scaling factor to the answer.
        addrat(ref px, pwr, precision);

        trimit(ref px, precision);

        // If number started out < 1 rescale answer to negative.
        if (fneglog)
        {
            (px)._pp._sign *= -1;
        }

        destroyrat(ref offset);
        destroyrat(ref pwr);
    }

    public void log10rat(ref PRAT px, int32_t precision)
    {
        lograt(ref px, precision);
        divrat(ref px, ln_ten, precision);
    }

    //
    // return if the given x is even number. The assumption here is its denominator is 1 and we are testing the numerator is
    // even or not
    bool IsEven(PRAT x, uint32_t radix, int32_t precision)
    {
        PRAT? tmp = null;
        bool bRet = false;

        duprat(ref tmp, x);
        divrat(ref tmp, rat_two, precision);
        fracrat(ref tmp, radix, precision);
        addrat(ref tmp, tmp, precision);
        subrat(ref tmp, rat_one, precision);
        if (RatLt(tmp, rat_zero, precision))
        {
            bRet = true;
        }

        destroyrat(ref tmp);
        return bRet;
    }

    //---------------------------------------------------------------------------
    //
    //  FUNCTION: powrat
    //
    //  ARGUMENTS: PRAT *px, PRAT y, uint32_t radix, int32_t precision
    //
    //  RETURN: none, sets *px to *px to the y.
    //
    //  EXPLANATION: Calculates the power of both px and
    //  handles special cases where px is a perfect root.
    //  Assumes, all checking has been done on validity of numbers.
    //
    //
    //---------------------------------------------------------------------------
    public void powrat(ref PRAT px, PRAT y, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        if (y is null)
        {
            throw new ArgumentNullException(nameof(y));
        }

        // Handle cases where px or y is 0 by calling powratcomp directly
        if (zerrat(px) || zerrat(y))
        {
            powratcomp(ref px, y, radix, precision);
            return;
        }

        // When y is 1, return px
        if (RatEqu(y, rat_one, precision))
        {
            return;
        }

        try
        {
            powratNumeratorDenominator(ref px, y, radix, precision);
        }
        catch (CalcErrException)
        {
            // If calculating the power using numerator/denominator
            // failed, fall back to the less accurate method of
            // passing in the original y
            powratcomp(ref px, y, radix, precision);
        }
        catch (ArithmeticException)
        {
            powratcomp(ref px, y, radix, precision);
        }
    }

    void powratNumeratorDenominator(ref PRAT px, PRAT y, uint32_t radix, int32_t precision)
    {
        // Prepare rationals
        PRAT? yNumerator = null;
        PRAT? yDenominator = null;
        duprat(ref yNumerator, rat_zero); // yNumerator._pq is 1 one
        duprat(ref yDenominator, rat_zero); // yDenominator._pq is 1 one
        dupnum(ref yNumerator._pp, y._pp);
        dupnum(ref yDenominator._pp, y._pq);

        // Calculate the following use the Powers of Powers rule:
        // px ^ (yNum/yDenom) == px ^ yNum ^ (1/yDenom)
        // 1. For px ^ yNum, we call powratcomp directly which will call ratpowi32
        //    and store the result in pxPowNum
        // 2. For pxPowNum ^ (1/yDenom), we call powratcomp
        // 3. Validate the result of 2 by adding/subtracting 0.5, flooring and call powratcomp with yDenom
        //    on the floored result.

        // 1. Initialize result.
        PRAT? pxPow = null;
        duprat(ref pxPow, px);

        // 2. Calculate pxPow = px ^ yNumerator
        // if yNumerator is not 1
        if (!RatEqu(yNumerator, rat_one, precision))
        {
            powratcomp(ref pxPow, yNumerator, radix, precision);
        }

        // 2. Calculate pxPowNumDenom = pxPowNum ^ (1/yDenominator),
        // if yDenominator is not 1
        if (!RatEqu(yDenominator, rat_one, precision))
        {
            // Calculate 1 over y
            PRAT? oneoveryDenom = null;
            duprat(ref oneoveryDenom, rat_one);
            divrat(ref oneoveryDenom, yDenominator, precision);

            // ##################################
            // Take the oneoveryDenom power
            // ##################################
            PRAT? originalResult = null;
            duprat(ref originalResult, pxPow);
            powratcomp(ref originalResult, oneoveryDenom, radix, precision);

            // ##################################
            // Round the originalResult to roundedResult
            // ##################################
            PRAT? roundedResult = null;
            duprat(ref roundedResult, originalResult);
            if (roundedResult._pp._sign == -1)
            {
                subrat(ref roundedResult, rat_half, precision);
            }
            else
            {
                addrat(ref roundedResult, rat_half, precision);
            }

            intrat(ref roundedResult, radix, precision);

            // ##################################
            // Take the yDenom power of the roundedResult.
            // ##################################
            PRAT? roundedPower = null;
            duprat(ref roundedPower, roundedResult);
            powratcomp(ref roundedPower, yDenominator, radix, precision);

            // ##################################
            // if roundedPower == px,
            // we found an exact power in roundedResult
            // ##################################
            if (RatEqu(roundedPower, pxPow, precision))
            {
                duprat(ref px, roundedResult);
            }
            else
            {
                duprat(ref px, originalResult);
            }

            destroyrat(ref oneoveryDenom);
            destroyrat(ref originalResult);
            destroyrat(ref roundedResult);
            destroyrat(ref roundedPower);
        }
        else
        {
            duprat(ref px, pxPow);
        }

        destroyrat(ref yNumerator);
        destroyrat(ref yDenominator);
        destroyrat(ref pxPow);
    }

    //---------------------------------------------------------------------------
    //
    //  FUNCTION: powratcomp
    //
    //  ARGUMENTS: PRAT *px, and PRAT y
    //
    //  RETURN: none, sets *px to *px to the y.
    //
    //  EXPLANATION: This uses x^y=e(y*ln(x)), or a more exact calculation where
    //  y is an integer.
    //  Assumes, all checking has been done on validity of numbers.
    //
    //
    //---------------------------------------------------------------------------
    void powratcomp(ref PRAT px, PRAT y, uint32_t radix, int32_t precision)
    {
        int32_t sign = SIGN(px);

        // Take the absolute value
        (px)._pp._sign = 1;
        (px)._pq._sign = 1;

        if (zerrat(px))
        {
            // *px is zero.
            if (RatLt(y, rat_zero, precision))
            {
                throw new CalcErrException(CalcErr.Domain);
            }
            else if (zerrat(y))
            {
                // *px and y are both zero, special case a 1 return.
                duprat(ref px, rat_one);
                // Ensure sign is positive.
                sign = 1;
            }
        }
        else
        {
            PRAT? pxint = null;
            duprat(ref pxint, px);
            subrat(ref pxint, rat_one, precision);
            if (RatGt(pxint, rat_negsmallest, precision) && RatLt(pxint, rat_smallest, precision) && (sign == 1))
            {
                // *px is one, special case a 1 return.
                duprat(ref px, rat_one);
                // Ensure sign is positive.
                sign = 1;
            }
            else
            {
                // Only do the exp if the number isn't zero or one
                PRAT? podd = null;
                duprat(ref podd, y);
                fracrat(ref podd, radix, precision);
                if (RatGt(podd, rat_negsmallest, precision) && RatLt(podd, rat_smallest, precision))
                {
                    // If power is an integer let ratpowi32 deal with it.
                    PRAT? iy = null;
                    duprat(ref iy, y);
                    subrat(ref iy, podd, precision);
                    int32_t inty = rattoi32(iy, radix, precision);

                    PRAT? plnx = null;
                    duprat(ref plnx, px);
                    lograt(ref plnx, precision);
                    mulrat(ref plnx, iy, precision);
                    if (RatGt(plnx, rat_max_exp, precision) || RatLt(plnx, rat_min_exp, precision))
                    {
                        // Don't attempt exp of anything large or small.A
                        destroyrat(ref plnx);
                        destroyrat(ref iy);
                        destroyrat(ref pxint);
                        destroyrat(ref podd);
                        throw new CalcErrException(CalcErr.Domain);
                    }

                    destroyrat(ref plnx);
                    ratpowi32(ref px, inty, precision);
                    if ((inty & 1) == 0)
                    {
                        sign = 1;
                    }

                    destroyrat(ref iy);
                }
                else
                {
                    // power is a fraction
                    if (sign == -1)
                    {
                        // Need to throw an error if the exponent has an even denominator.
                        // As a first step, the numerator and denominator must be divided by 2 as many times as
                        //     possible, so that 2/6 is allowed.
                        // If the final numerator is still even, the end result should be positive.
                        PRAT? pNumerator = null;
                        PRAT? pDenominator = null;
                        bool fBadExponent = false;

                        // Get the numbers in arbitrary precision rational number format
                        duprat(ref pNumerator, rat_zero); // pNumerator._pq is 1 one
                        duprat(ref pDenominator, rat_zero); // pDenominator._pq is 1 one

                        dupnum(ref pNumerator._pp, y._pp);
                        pNumerator._pp._sign = 1;
                        dupnum(ref pDenominator._pp, y._pq);
                        pDenominator._pp._sign = 1;

                        while (IsEven(pNumerator, radix, precision) &&
                               IsEven(pDenominator, radix, precision)) // both Numerator & denominator is even
                        {
                            divrat(ref pNumerator, rat_two, precision);
                            divrat(ref pDenominator, rat_two, precision);
                        }

                        if (IsEven(pDenominator, radix, precision)) // denominator is still even
                        {
                            fBadExponent = true;
                        }

                        if (IsEven(pNumerator, radix, precision)) // numerator is still even
                        {
                            sign = 1;
                        }

                        destroyrat(ref pNumerator);
                        destroyrat(ref pDenominator);

                        if (fBadExponent)
                        {
                            throw new CalcErrException(CalcErr.Domain);
                        }
                    }
                    else
                    {
                        // If the exponent is not odd disregard the sign.
                        sign = 1;
                    }

                    lograt(ref px, precision);
                    mulrat(ref px, y, precision);
                    exprat(ref px, radix, precision);
                }

                destroyrat(ref podd);
            }

            destroyrat(ref pxint);
        }

        (px)._pp._sign *= sign;
    }

    // Methods to replace the C++ macros
    private static void ABSRAT(PRAT x)
    {
        x._pp._sign = 1;
        x._pq._sign = 1;
    }

    private static void NEGATE(PRAT x)
    {
        x._pp._sign *= -1;
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: factrat, _gamma, gamma
    //
    //  ARGUMENTS:  x PRAT representation of number to take the sine of
    //
    //  RETURN: factorial of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //      n
    //     ___    2j
    //   n \  ]  A       1          A
    //  A   \   -----[ ---- - ---------------]
    //      /   (2j)!  n+2j   (n+2j+1)(2j+1)
    //     /__]
    //     j=0
    //
    //                        / oo
    //                        |    n-1 -x     __
    //  This was derived from |   x   e  dx = |
    //                        |               | (n) { = (n-1)! for +integers}
    //                        / 0
    //
    //  It can be shown that the above series is within precision if A is chosen
    //  big enough.
    //                          A    n  precision
    //  Based on the relation ne  = A 10            A was chosen as
    //
    //             precision
    //  A = ln(Base         /n)+1
    //  A += n*ln(A)  This is close enough for precision > base and n < 1.5
    //
    //
    //-----------------------------------------------------------------------------
    void _gamma(ref PRAT pn, uint32_t radix, int32_t precision)
    {
        PRAT? factorial = null;
        PNUMBER? count = null;
        PRAT? tmp = null;
        PRAT? one_pt_five = null;
        PRAT? a = null;
        PRAT? a2 = null;
        PRAT? term = null;
        PRAT? sum = null;
        PRAT? err = null;
        PRAT? mpy = null;

        // Set up constants and initial conditions
        PRAT? ratprec = i32torat(precision);

        // Find the best 'A' for convergence to the required precision.
        a = i32torat((int32_t)radix);
        lograt(ref a, precision);
        mulrat(ref a, ratprec, precision);

        // Really is -ln(n)+1, but -ln(n) will be < 1
        // if we scale n between 0.5 and 1.5
        addrat(ref a, rat_two, precision);
        duprat(ref tmp, a);
        lograt(ref tmp, precision);
        mulrat(ref tmp, pn, precision);
        addrat(ref a, tmp, precision);
        addrat(ref a, rat_one, precision);

        // Calculate the necessary bump in precision and up the precision.
        // The following code is equivalent to
        // precision += ln(exp(a)*pow(a,n+1.5))-ln(radix));
        duprat(ref tmp, pn);
        one_pt_five = i32torat(3);
        divrat(ref one_pt_five, rat_two, precision);
        addrat(ref tmp, one_pt_five, precision);
        duprat(ref term, a);
        powratcomp(ref term, tmp, radix, precision);
        duprat(ref tmp, a);
        exprat(ref tmp, radix, precision);
        mulrat(ref term, tmp, precision);
        lograt(ref term, precision);
        PRAT ratRadix = i32torat((int32_t)radix);
        duprat(ref tmp, ratRadix);
        lograt(ref tmp, precision);
        subrat(ref term, tmp, precision);
        precision += rattoi32(term, radix, precision);

        // Set up initial terms for series, refer to series in above comment block.
        duprat(ref factorial, rat_one); // Start factorial out with one
        count = i32tonum(0, BASEX);

        duprat(ref mpy, a);
        powratcomp(ref mpy, pn, radix, precision);
        // a2=a^2
        duprat(ref a2, a);
        mulrat(ref a2, a, precision);

        // sum=(1/n)-(a/(n+1))
        duprat(ref sum, rat_one);
        divrat(ref sum, pn, precision);
        duprat(ref tmp, pn);
        addrat(ref tmp, rat_one, precision);
        duprat(ref term, a);
        divrat(ref term, tmp, precision);
        subrat(ref sum, term, precision);

        duprat(ref err, ratRadix);
        NEGATE(ratprec);
        powratcomp(ref err, ratprec, radix, precision);
        divrat(ref err, ratRadix, precision);

        // Just get something not tiny in term
        duprat(ref term, rat_two);

        // Loop until precision is reached, or asked to halt.
        while (!zerrat(term) && RatGt(term, err, precision))
        {
            addrat(ref pn, rat_two, precision);

            // WARNING: mixing numbers and rationals here.
            // for speed and efficiency.
            INC(ref count);
            mulnumx(ref (factorial._pp), count);
            INC(ref count);
            mulnumx(ref (factorial._pp), count);

            divrat(ref factorial, a2, precision);

            duprat(ref tmp, pn);
            addrat(ref tmp, rat_one, precision);
            destroyrat(ref term);
            createrat(ref term);
            dupnum(ref term._pp, count);
            dupnum(ref term._pq, num_one);
            addrat(ref term, rat_one, precision);
            mulrat(ref term, tmp, precision);
            duprat(ref tmp, a);
            divrat(ref tmp, term, precision);

            duprat(ref term, rat_one);
            divrat(ref term, pn, precision);
            subrat(ref term, tmp, precision);

            divrat(ref term, factorial, precision);
            addrat(ref sum, term, precision);
            ABSRAT(term);
        }

        // Multiply by factor.
        mulrat(ref sum, mpy, precision);

        // And cleanup
        destroyrat(ref ratprec);
        destroyrat(ref err);
        destroyrat(ref term);
        destroyrat(ref a);
        destroyrat(ref a2);
        destroyrat(ref tmp);
        destroyrat(ref one_pt_five);

        destroynum(ref count);

        destroyrat(ref factorial);
        duprat(ref pn, sum);
        destroyrat(ref sum);
    }

    public void factrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        PRAT? fact = null;
        PRAT? frac = null;
        PRAT? neg_rat_one = null;

        if (RatGt(px, rat_max_fact, precision) || RatLt(px, rat_min_fact, precision))
        {
            // Don't attempt factorial of anything too large or small.
            throw new CalcErrException(CalcErr.Overflow);
        }

        duprat(ref fact, rat_one);

        duprat(ref neg_rat_one, rat_one);
        neg_rat_one._pp._sign *= -1;

        duprat(ref frac, px);
        fracrat(ref frac, radix, precision);

        // Check for negative integers and throw an error.
        if ((zerrat(frac) || (LOGRATRADIX(frac) <= -precision)) && (SIGN(px) == -1))
        {
            throw new CalcErrException(CalcErr.Domain);
        }
        while (RatGt(px, rat_zero, precision) && (LOGRATRADIX(px) > -precision))
        {
            mulrat(ref fact, px, precision);
            subrat(ref px, rat_one, precision);
        }

        // Added to make numbers 'close enough' to integers use integer factorial.
        if (LOGRATRADIX(px) <= -precision)
        {
            duprat(ref px, rat_zero);
            intrat(ref fact, radix, precision);
        }

        while (RatLt(px, neg_rat_one, precision))
        {
            addrat(ref px, rat_one, precision);
            divrat(ref fact, px, precision);
        }

        if (RatNeq(px, rat_zero, precision))
        {
            addrat(ref px, rat_one, precision);
            _gamma(ref px, radix, precision);
            mulrat(ref px, fact, precision);
        }
        else
        {
            duprat(ref px, fact);
        }

        destroyrat(ref fact);
        destroyrat(ref frac);
        destroyrat(ref neg_rat_one);
    }

    // Scales the angle based on the angle type (radians, degrees, gradians)
    void ascalerat(ref PRAT pa, AngleType angletype, int32_t precision)
    {
        switch (angletype)
        {
            case AngleType.Radians:
                break;
            case AngleType.Degrees:
                divrat(ref pa, two_pi, precision);
                mulrat(ref pa, rat_360, precision);
                break;
            case AngleType.Gradians:
                divrat(ref pa, two_pi, precision);
                mulrat(ref pa, rat_400, precision);
                break;
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: asinrat, _asinrat
    //
    //  ARGUMENTS: x PRAT representation of number to take the inverse
    //    sine of
    //  RETURN: asin of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___
    //   \  ]                                                   2 2
    //    \   thisterm  ; where thisterm   = thisterm  * (2j+1) X
    //    /           j                 j+1          j   (2j+2)*(2j+3)
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   If abs(x) > 0.85 then an alternate form is used
    //      pi/2-sgn(x)*asin(sqrt(1-x^2)
    //
    //-----------------------------------------------------------------------------
    // Helper function for asin Taylor series term
    void ASIN_RAT_NEXTTERM(ref RAT thisterm, ref RAT xx, ref NUMBER n2, int32_t precision, ref RAT pret)
    {
        mulrat(ref thisterm, xx, precision);
        MULNUM(ref n2, thisterm);
        MULNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        addrat(ref pret, thisterm, precision);
    }

    void _asinrat(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        duprat(ref pret, px);
        duprat(ref thisterm, px);
        dupnum(ref n2, num_one);

        do
        {
            ASIN_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void asinanglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        asinrat(ref pa, radix, precision);
        ascalerat(ref pa, angletype, precision);
    }

    public void asinrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        PRAT? pret = null;
        PRAT? phack = null;
        int32_t sgn = SIGN(px);

        px._pp._sign = 1;
        px._pq._sign = 1;

        // Avoid the really bad part of the asin curve near +/-1.
        duprat(ref phack, px);
        subrat(ref phack, rat_one, precision);
        // Since px might be epsilon near zero we must set it to zero.
        if (rat_le(phack, rat_smallest, precision) && rat_ge(phack, rat_negsmallest, precision))
        {
            destroyrat(ref phack);
            duprat(ref px, pi_over_two);
        }
        else
        {
            destroyrat(ref phack);
            if (RatGt(px, pt_eight_five, precision))
            {
                if (RatGt(px, rat_one, precision))
                {
                    subrat(ref px, rat_one, precision);
                    if (RatGt(px, rat_smallest, precision))
                    {
                        throw new CalcErrException(CalcErr.Domain);
                    }
                    else
                    {
                        duprat(ref px, rat_one);
                    }
                }
                duprat(ref pret, px);
                mulrat(ref px, pret, precision);
                px._pp._sign *= -1;
                addrat(ref px, rat_one, precision);
                rootrat(ref px, rat_two, radix, precision);
                _asinrat(ref px, precision);
                px._pp._sign *= -1;
                addrat(ref px, pi_over_two, precision);
                destroyrat(ref pret);
            }
            else
            {
                _asinrat(ref px, precision);
            }
        }
        px._pp._sign = sgn;
        px._pq._sign = 1;
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: acosrat, _acosrat
    //
    //  ARGUMENTS: x PRAT representation of number to take the inverse
    //    cosine of
    //  RETURN: acos of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___
    //   \  ]                                                   2 2
    //    \   thisterm  ; where thisterm   = thisterm  * (2j+1) X
    //    /           j                 j+1          j   (2j+2)*(2j+3)
    //   /__]
    //   j=0
    //
    //   thisterm  = 1 ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   In this case pi/2-asin(x) is used.  At least for now _acosrat isn't
    //   called.
    //
    //-----------------------------------------------------------------------------
    void _acosrat(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        createrat(ref thisterm);
        thisterm._pp = i32tonum(1, BASEX);
        thisterm._pq = i32tonum(1, BASEX);

        dupnum(ref n2, num_one);

        do
        {
            ASIN_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void acosanglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        acosrat(ref pa, radix, precision);
        ascalerat(ref pa, angletype, precision);
    }

    public void acosrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        int32_t sgn = SIGN(px);

        px._pp._sign = 1;
        px._pq._sign = 1;

        if (RatEqu(px, rat_one, precision))
        {
            if (sgn == -1)
            {
                duprat(ref px, _pi);
            }
            else
            {
                duprat(ref px, rat_zero);
            }
        }
        else
        {
            px._pp._sign = sgn;
            asinrat(ref px, radix, precision);
            px._pp._sign *= -1;
            addrat(ref px, pi_over_two, precision);
        }
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: atanrat, _atanrat
    //
    //  ARGUMENTS: x PRAT representation of number to take the inverse
    //             tangent of
    //
    //  RETURN: atan of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___
    //   \  ]                                                   2
    //    \   thisterm  ; where thisterm   = thisterm  * (2j)*X (-1^j)
    //    /           j                 j+1          j   (2j+2)
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   If abs(x) > 0.85 then an alternate form is used
    //      asin(x/sqrt(1+x^2))
    //
    //   And if abs(x) > 2.0 then this form is used:
    //
    //   pi/2 - atan(1/x)
    //
    //-----------------------------------------------------------------------------

    // Helper function for atan Taylor series term
    void ATAN_RAT_NEXTTERM(ref RAT thisterm, ref RAT xx, ref NUMBER n2, int32_t precision, ref RAT pret)
    {
        mulrat(ref thisterm, xx, precision);
        MULNUM(ref n2, thisterm);
        INC(ref n2);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        addrat(ref pret, thisterm, precision);
    }

    void _atanrat(ref PRAT px, int32_t precision)
    {
        CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);

        duprat(ref pret, px);
        duprat(ref thisterm, px);

        dupnum(ref n2, num_one);

        xx._pp._sign *= -1;

        do
        {
            ATAN_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
        } while (!SMALL_ENOUGH_RAT(thisterm, precision));

        DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
    }

    public void atananglerat(ref PRAT pa, AngleType angletype, uint32_t radix, int32_t precision)
    {
        atanrat(ref pa, radix, precision);
        ascalerat(ref pa, angletype, precision);
    }

    public void atanrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        if (px is null)
        {
            throw new ArgumentNullException(nameof(px));
        }

        PRAT? tmpx = null;
        int32_t sgn = SIGN(px);

        px._pp._sign = 1;
        px._pq._sign = 1;

        if (RatGt(px, pt_eight_five, precision))
        {
            if (RatGt(px, rat_two, precision))
            {
                px._pp._sign = sgn;
                px._pq._sign = 1;
                duprat(ref tmpx, rat_one);
                divrat(ref tmpx, px, precision);
                _atanrat(ref tmpx, precision);
                tmpx._pp._sign = sgn;
                tmpx._pq._sign = 1;
                duprat(ref px, pi_over_two);
                subrat(ref px, tmpx, precision);
                destroyrat(ref tmpx);
            }
            else
            {
                px._pp._sign = sgn;
                duprat(ref tmpx, px);
                mulrat(ref tmpx, px, precision);
                addrat(ref tmpx, rat_one, precision);
                rootrat(ref tmpx, rat_two, radix, precision);
                divrat(ref px, tmpx, precision);
                destroyrat(ref tmpx);
                asinrat(ref px, radix, precision);
                px._pp._sign = sgn;
                px._pq._sign = 1;
            }
        }
        else
        {
            px._pp._sign = sgn;
            px._pq._sign = 1;
            _atanrat(ref px, precision);
        }
        if (RatGt(px, pi_over_two, precision))
        {
            subrat(ref px, _pi, precision);
        }
    }

    // Helper function for asinh Taylor series term - implements the NEXTTERM macro for asinh
    void ASINH_RAT_NEXTTERM(ref RAT thisterm, ref RAT xx, ref NUMBER n2, int32_t precision, ref RAT pret)
    {
        // First multiply by xx (the -x² value)
        mulrat(ref thisterm, xx, precision);

        // Execute the operations from the d parameter: MULNUM(n2) MULNUM(n2) INC(n2) DIVNUM(n2) INC(n2) DIVNUM(n2)
        MULNUM(ref n2, thisterm);
        MULNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);
        INC(ref n2);
        DIVNUM(ref n2, thisterm);

        // Add the result to pret
        addrat(ref pret, thisterm, precision);
    }

    //-----------------------------------------------------------------------------
    //
    //  FUNCTION: asinhrat
    //
    //  ARGUMENTS:  x PRAT representation of number to take the inverse
    //    hyperbolic sine of
    //  RETURN: asinh of x in PRAT form.
    //
    //  EXPLANATION: This uses Taylor series
    //
    //    n
    //   ___                                                   2 2
    //   \  ]                                           -(2j+1) X
    //    \   thisterm  ; where thisterm   = thisterm  * ---------
    //    /           j                 j+1          j   (2j+2)*(2j+3)
    //   /__]
    //   j=0
    //
    //   thisterm  = X ;  and stop when thisterm < precision used.
    //           0                              n
    //
    //   For abs(x) < .85, and
    //
    //   asinh(x) = log(x+sqrt(x^2+1))
    //
    //   For abs(x) >= .85
    //
    //-----------------------------------------------------------------------------
    public void asinhrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT? neg_pt_eight_five = null;

        duprat(ref neg_pt_eight_five, pt_eight_five);
        neg_pt_eight_five._pp._sign *= -1;
        if (RatGt(px, pt_eight_five, precision) || RatLt(px, neg_pt_eight_five, precision))
        {
            PRAT? ptmp = null;
            duprat(ref ptmp, px);
            mulrat(ref ptmp, px, precision);
            addrat(ref ptmp, rat_one, precision);
            rootrat(ref ptmp, rat_two, radix, precision);
            addrat(ref px, ptmp, precision);
            lograt(ref px, precision);
            destroyrat(ref ptmp);
        }
        else
        {
            CREATETAYLOR(ref px, precision, out var xx, out var n2, out var pret, out var thisterm);
            xx._pp._sign *= -1;

            duprat(ref pret, px);
            duprat(ref thisterm, px);

            dupnum(ref n2, num_one);

            do
            {
                ASINH_RAT_NEXTTERM(ref thisterm, ref xx, ref n2, precision, ref pret);
            } while (!SMALL_ENOUGH_RAT(thisterm, precision));

            DESTROYTAYLOR(ref px, ref n2, ref xx, ref thisterm, pret, precision);
        }
        destroyrat(ref neg_pt_eight_five);
    }

