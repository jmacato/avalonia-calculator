    //---------------------------------------------------------------------------
    //
    //  function: scale
    //
    //  ARGUMENTS:  pointer to x PRAT representation of number, and scaling factor
    //
    //  RETURN: no return, value x PRAT is smashed with a scaled number in the
    //          range of the scalefact.
    //
    //---------------------------------------------------------------------------

    public void scale(ref PRAT px, PRAT scalefact, uint32_t radix, int32_t precision)
    {
        PRAT pret = null;
        duprat(ref pret, px);

        // Logscale is a quick way to tell how much extra precision is needed for
        // scaling by scalefact.
        int32_t logscale = g_ratio * ((pret.pp.cdigit + pret.pp.exp) - (pret.pq.cdigit + pret.pq.exp));
        if (logscale > 0)
        {
            precision += logscale;
        }

        divrat(ref pret, scalefact, precision);
        intrat(ref pret, radix, precision);
        mulrat(ref pret, scalefact, precision);
        pret.pp.sign *= -1;
        addrat(ref px, pret, precision);

        destroyrat(ref pret);
    }

    //---------------------------------------------------------------------------
    //
    //  function: scale2pi
    //
    //  ARGUMENTS:  pointer to x PRAT representation of number
    //
    //  RETURN: no return, value x PRAT is smashed with a scaled number in the
    //          range of 0..2pi
    //
    //---------------------------------------------------------------------------

    public void scale2pi(ref PRAT px, uint32_t radix, int32_t precision)
    {
        PRAT pret = null;
        PRAT my_two_pi = null;
        duprat(ref pret, px);

        // Logscale is a quick way to tell how much extra precision is needed for
        // scaling by 2 pi.
        int32_t logscale = g_ratio * ((pret.pp.cdigit + pret.pp.exp) - (pret.pq.cdigit + pret.pq.exp));
        if (logscale > 0)
        {
            precision += logscale;
            duprat(ref my_two_pi, rat_half);
            asinrat(ref my_two_pi, radix, precision);
            mulrat(ref my_two_pi, rat_six, precision);
            mulrat(ref my_two_pi, rat_two, precision);
        }
        else
        {
            duprat(ref my_two_pi, two_pi);
            logscale = 0;
        }

        divrat(ref pret, my_two_pi, precision);
        intrat(ref pret, radix, precision);
        mulrat(ref pret, my_two_pi, precision);
        pret.pp.sign *= -1;
        addrat(ref px, pret, precision);

        destroyrat(ref my_two_pi);
        destroyrat(ref pret);
    }

    //---------------------------------------------------------------------------
    //
    //  FUNCTION: inbetween
    //
    //  ARGUMENTS:  PRAT *px, and PRAT range.
    //
    //  RETURN: none, changes *px to -/+range, if px is outside -range..+range
    //
    //---------------------------------------------------------------------------

    public void inbetween(ref PRAT px, PRAT range, int32_t precision)
    {
        if (rat_gt(px, range, precision))
        {
            duprat(ref px, range);
        }
        else
        {
            range.pp.sign *= -1;
            if (rat_lt(px, range, precision))
            {
                duprat(ref px, range);
            }

            range.pp.sign *= -1;
        }
    }

