    //
    //  FUNCTION: _dumprawnum
    //
    //  ARGUMENTS:  const wchar *name of variable, PNUMBER num, output stream out
    //
    //  RETURN: none, prints the results of a dump of the internal structures
    //          of a PNUMBER, suitable for READRAWNUM to stderr.
    //
    //---------------------------------------------------------------------------

    public void _dumprawnum(string varname, PNUMBER num, TextWriter output)
    {
        output.WriteLine($"NUMBER {varname} = {{");
        output.WriteLine($"\t{num.sign},");
        output.WriteLine($"\t{num.cdigit},");
        output.WriteLine($"\t{num.exp},");
        output.Write("\t{ ");

        for (int i = 0; i < num.cdigit; i++)
        {
            output.Write($" {num.mant[i]},");
        }

        output.WriteLine("}");
        output.WriteLine("};");
    }

