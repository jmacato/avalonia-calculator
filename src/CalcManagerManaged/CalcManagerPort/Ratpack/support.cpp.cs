//----------------------------------------------------------------------------
//
//  FUNCTION: ChangeConstants
//
//  ARGUMENTS:  base changing to, and precision to use.
//
//  RETURN: None
//
//  SIDE EFFECTS: sets a mess of constants.
//
//
//----------------------------------------------------------------------------

    public void ChangeConstants(uint32_t radix, int32_t precision)
    {
        // ratio is set to the number of digits in the current radix, you can get
        // in the internal BASEX radix, this is important for length calculations
        // in translating from radix to BASEX and back.

        g_ratio = (int32_t)(Math.Ceiling(BASEXPWR / Math.Log(radix, 2))) - 1;

        destroyrat(ref rat_nRadix);
        rat_nRadix = i32torat((int32_t)radix);

        // Check to see what we have to recalculate and what we don't
        if (cbitsofprecision < (g_ratio * (int32_t)(radix) * precision))
        {
            g_ftrueinfinite = false;

            INIT_AND_DUMP_RAW_NUM_IF_NULL(ref num_one, 1);
            INIT_AND_DUMP_RAW_NUM_IF_NULL(ref num_two, 2);
            INIT_AND_DUMP_RAW_NUM_IF_NULL(ref num_five, 5);
            INIT_AND_DUMP_RAW_NUM_IF_NULL(ref num_six, 6);
            INIT_AND_DUMP_RAW_NUM_IF_NULL(ref num_ten, 10);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_six, 6);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_two, 2);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_zero, 0);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_one, 1);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_neg_one, -1);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_ten, 10);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_word, 0xffff);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_word, 0xff);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_400, 400);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_360, 360);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_200, 200);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_180, 180);
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_max_exp, 100000);

            // 3248, is the max number for which calc is able to compute factorial, after that it is unable to compute due to overflow.
            // Hence restricted factorial range as at most 3248.Beyond that calc will throw overflow error immediately.
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_max_fact, 3249);

            // -1000, is the min number for which calc is able to compute factorial, after that it takes too long to compute.
            INIT_AND_DUMP_RAW_RAT_IF_NULL(ref rat_min_fact, -1000);

            duprat(ref rat_smallest, rat_nRadix);
            ratpowi32(ref rat_smallest, -precision, precision);
            duprat(ref rat_negsmallest, rat_smallest);
            rat_negsmallest.pp.sign = -1;
            DUMPRAWRAT(rat_smallest);
            DUMPRAWRAT(rat_negsmallest);

            if (rat_half == null)
            {
                createrat(ref rat_half);
                dupnum(ref rat_half.pp, num_one);
                dupnum(ref rat_half.pq, num_two);
                DUMPRAWRAT(rat_half);
            }

            if (pt_eight_five == null)
            {
                createrat(ref pt_eight_five);
                pt_eight_five.pp = i32tonum(85, BASEX);
                pt_eight_five.pq = i32tonum(100, BASEX);
                DUMPRAWRAT(pt_eight_five);
            }

            duprat(ref rat_qword, rat_two);
            numpowi32(ref (rat_qword.pp), 64, BASEX, precision);
            subrat(ref rat_qword, rat_one, precision);
            DUMPRAWRAT(rat_qword);

            duprat(ref rat_dword, rat_two);
            numpowi32(ref (rat_dword.pp), 32, BASEX, precision);
            subrat(ref rat_dword, rat_one, precision);
            DUMPRAWRAT(rat_dword);

            duprat(ref rat_max_i32, rat_two);
            numpowi32(ref (rat_max_i32.pp), 31, BASEX, precision);
            duprat(ref rat_min_i32, rat_max_i32);
            subrat(ref rat_max_i32, rat_one, precision); // rat_max_i32 = 2^31 -1
            DUMPRAWRAT(rat_max_i32);

            rat_min_i32.pp.sign *= -1; // rat_min_i32 = -2^31
            DUMPRAWRAT(rat_min_i32);

            duprat(ref rat_min_exp, rat_max_exp);
            rat_min_exp.pp.sign *= -1;
            DUMPRAWRAT(rat_min_exp);

            cbitsofprecision = unchecked(g_ratio * (int32_t)radix * precision);

            // Apparently when dividing 180 by pi, another (interna) digit of
            // precision is needed.
            int32_t extraPrecision = precision + g_ratio;
            duprat(ref pi, rat_half);
            asinrat(ref pi, radix, extraPrecision);
            mulrat(ref pi, rat_six, extraPrecision);
            DUMPRAWRAT(pi);

            duprat(ref two_pi, pi);
            duprat(ref pi_over_two, pi);
            duprat(ref one_pt_five_pi, pi);
            addrat(ref two_pi, pi, extraPrecision);
            DUMPRAWRAT(two_pi);

            divrat(ref pi_over_two, rat_two, extraPrecision);
            DUMPRAWRAT(pi_over_two);

            addrat(ref one_pt_five_pi, pi_over_two, extraPrecision);
            DUMPRAWRAT(one_pt_five_pi);

            duprat(ref e_to_one_half, rat_half);
            _exprat(ref e_to_one_half, extraPrecision);
            DUMPRAWRAT(e_to_one_half);

            duprat(ref rat_exp, rat_one);
            _exprat(ref rat_exp, extraPrecision);
            DUMPRAWRAT(rat_exp);

            // WARNING: remember lograt uses exponent constants calculated above...

            duprat(ref ln_ten, rat_ten);
            lograt(ref ln_ten, extraPrecision);
            DUMPRAWRAT(ln_ten);

            duprat(ref ln_two, rat_two);
            lograt(ref ln_two, extraPrecision);
            DUMPRAWRAT(ln_two);

            destroyrat(ref rad_to_deg);
            rad_to_deg = i32torat(180);
            divrat(ref rad_to_deg, pi, extraPrecision);
            DUMPRAWRAT(rad_to_deg);

            destroyrat(ref rad_to_grad);
            rad_to_grad = i32torat(200);
            divrat(ref rad_to_grad, pi, extraPrecision);
            DUMPRAWRAT(rad_to_grad);
        }
        else
        {
            _readconstants();

            duprat(ref rat_smallest, rat_nRadix);
            ratpowi32(ref rat_smallest, -precision, precision);
            duprat(ref rat_negsmallest, rat_smallest);
            rat_negsmallest.pp.sign = -1;
        }
    }

//----------------------------------------------------------------------------
//
//  FUNCTION: intrat
//
//  ARGUMENTS:  pointer to x PRAT representation of number
//
//  RETURN: no return value x PRAT is smashed with integral number
//
//
//----------------------------------------------------------------------------

    public void intrat(ref PRAT px, uint32_t radix, int32_t precision)
    {
        // Only do the intrat operation if number is nonzero.
        // and only if the bottom part is not one.
        if (!zernum((px).pp) && !equnum((px).pq, num_one))
        {
            flatrat(ref px, radix, precision);

            // Subtract the fractional part of the rational
            PRAT pret = null;
            duprat(ref pret, px);
            remrat(ref pret, rat_one);

            // Flatten pret in case it's not aligned with px after remrat operation
            if (!equnum((px).pq, pret.pq))
            {
                flatrat(ref pret, radix, precision);
            }

            subrat(ref px, pret, precision);
            destroyrat(ref pret);

            // Simplify the value if possible to resolve rounding errors
            flatrat(ref px, radix, precision);
        }
    }

    //---------------------------------------------------------------------------
    //
    //  FUNCTION: rat_equ
    //
    //  ARGUMENTS:  PRAT a and PRAT b
    //
    //  RETURN: true if equal false otherwise.
    //
    //
    //---------------------------------------------------------------------------
    public bool rat_equ(PRAT a, PRAT b, int32_t precision)

    {
        PRAT rattmp = null;
        duprat(ref rattmp, a);
        rattmp.pp.sign *= -1;
        addrat(ref rattmp, b, precision);
        bool bret = zernum(rattmp.pp);
        destroyrat(ref rattmp);
        return (bret);
    }

